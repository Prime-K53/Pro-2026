// D-05/R9 — SERVICE-LEVEL PostgreSQL concurrency harness.
//
// Calls the REAL aiService functions over independent `pg` Pool connections,
// each service invocation wrapped in a real BEGIN/COMMIT/ROLLBACK transaction.
// Skips unless PG_URL is set and the `pg` driver is installed. NEVER targets
// production: only the disposable schema created here is used.
//
// Run: PG_URL=postgres://user:pass@host:port/db node --import tsx tests/pg/concurrency.mjs
//
// Each scenario starts from deterministic, company-scoped state (see
// resetCompany): only the disposable test companies' rows/counters are reset,
// never shared schema, migration history, or another company's data. The
// harness is safe to rerun after a partial failure.
//
// Production service functions exercised per scenario:
//   1  reserveAttempt                         (final-token reservation race)
//   2  reserveAttempt                         (20 concurrent reservations <= limit)
//   3  reserveAttempt + settleAttempt         (duplicate settlement counted once)
//   4  reserveAttempt + settleAttempt + recordProviderFailure (settle vs release)
//   5  reserveAttempt + settleAttempt + recoverUnresolvedAttempts (settle vs recovery)
//   6  recoverUnresolvedAttempts              (two recovery workers)
//   7  reserveAttempt + recoverUnresolvedAttempts (recovery vs live invocation)
//   8  recoverAllUnresolved -> getSystemRecoveryUserId + recoverUnresolvedAttempts
//                                             (two scheduler instances)
//   9  reserveAttempt                         (two-company isolation)
//  10  getSystemRecoveryUserId                (concurrent recovery-identity provisioning)

const url = process.env.PG_URL;
if (!url) { console.log('SKIP: PG_URL not set (PostgreSQL concurrency UNVERIFIED)'); process.exit(0); }
let pg;
try { pg = (await import('pg')).default; } catch { console.log('SKIP: pg driver not installed (PostgreSQL concurrency UNVERIFIED)'); process.exit(0); }

const svc = await import(new URL('../../src/server/services/aiService.ts', import.meta.url).href);
const { Pool } = pg;
const pool = new Pool({ connectionString: url, max: 30 });
{
  const c = await pool.connect();
  const ver = (await c.query('SELECT version()')).rows[0].version;
  c.release();
  console.log('PostgreSQL:', ver.split(',')[0], '| pool max:', 30);
}

// ── Disposable test schema (mirrors only the columns the services touch) ──
{
  const c = await pool.connect();
  await c.query(`
    DROP TABLE IF EXISTS ai_usage_attempts; DROP TABLE IF EXISTS ai_budget_usage;
    DROP TABLE IF EXISTS ai_budgets; DROP TABLE IF EXISTS ai_audit_logs;
    DROP TABLE IF EXISTS users; DROP TABLE IF EXISTS companies;

    CREATE TABLE companies (id BIGINT PRIMARY KEY);

    CREATE TABLE users (
      id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username      TEXT NOT NULL,
      email         TEXT NOT NULL,
      display_name  TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      is_active     BOOLEAN NOT NULL DEFAULT TRUE,
      created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE UNIQUE INDEX users_username_uniq ON users (username);

    CREATE TABLE ai_audit_logs (
      id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      company_id       BIGINT NOT NULL,
      user_id          BIGINT NOT NULL,
      action           TEXT NOT NULL,
      query            TEXT,
      response_summary TEXT,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE TABLE ai_budgets (
      company_id BIGINT PRIMARY KEY,
      monthly_token_limit BIGINT NOT NULL,
      monthly_cost_limit NUMERIC(19,4) NOT NULL DEFAULT 0,
      cost_per_1k_tokens NUMERIC(19,4) NOT NULL DEFAULT 0
    );
    CREATE TABLE ai_budget_usage (
      company_id BIGINT NOT NULL, period TEXT NOT NULL,
      reserved_tokens BIGINT NOT NULL DEFAULT 0, settled_tokens BIGINT NOT NULL DEFAULT 0,
      updated_at TIMESTAMPTZ DEFAULT NOW(), PRIMARY KEY (company_id, period)
    );
    CREATE TABLE ai_usage_attempts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      company_id BIGINT NOT NULL, request_id UUID NOT NULL, attempt_no INT NOT NULL,
      provider TEXT NOT NULL, model TEXT, reservation_tokens INT NOT NULL DEFAULT 0,
      state TEXT NOT NULL DEFAULT 'reserved', prompt_tokens INT, completion_tokens INT,
      total_tokens INT, usage_source TEXT, provider_request_id TEXT, error TEXT,
      reserved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), settled_at TIMESTAMPTZ,
      period TEXT NOT NULL, UNIQUE(request_id, attempt_no)
    );
  `);
  c.release();
}

// ── Faithful transaction adapter ─────────────────────────────────────────
// Every service invocation runs on its OWN pooled connection inside a real
// BEGIN ... COMMIT, rolling back on error. Company scoping is applied with the
// same `app.current_company_id` session setting production uses; the services
// additionally filter every statement by `company_id = $1`.
const runTx = async (fn, { companyId } = {}) => {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    if (companyId !== undefined) {
      await client.query(`SELECT set_config('app.current_company_id', $1, true)`, [String(companyId)]);
    }
    const tx = {
      query: (sql, params) => client.query(sql, params),
      exec: (sql) => client.query(sql),
    };
    const out = await fn(client, tx);
    await client.query('COMMIT');
    return out;
  } catch (e) {
    try { await client.query('ROLLBACK'); } catch { /* connection already aborted */ }
    throw e;
  } finally {
    client.release();
  }
};
const companyTx = (companyId, fn) => runTx(fn, { companyId });
const systemTx = (fn) => runTx(fn);
// Minimal ServerDatabase-shaped adapter for the scheduler-level entry points.
const makeDb = () => ({
  withSystemDb: (fn) => systemTx(fn),
  withCompanyDb: (companyId, fn) => companyTx(companyId, fn),
});

const A = 900001, B = 900002, LIMIT = 5000;
const PERIOD = new Date().toISOString().slice(0, 7);
const msgs = [{ role: 'user', content: 'x'.repeat(40) }];
const estimate = svc.estimateRequestTokens(msgs);

const counters = (co) => companyTx(co, async (_c, t) =>
  (await t.query(`SELECT reserved_tokens, settled_tokens FROM ai_budget_usage WHERE company_id=$1 AND period=$2`, [co, PERIOD])).rows[0]
  || { reserved_tokens: 0, settled_tokens: 0 });
const auditCount = (co) => systemTx(async (_c, t) =>
  Number((await t.query(`SELECT COUNT(*)::text AS cnt FROM ai_audit_logs WHERE company_id=$1 AND action='AI_RECOVERY'`, [co])).rows[0].cnt));
const attemptState = (co, id) => systemTx(async (_c, t) =>
  (await t.query(`SELECT state FROM ai_usage_attempts WHERE company_id=$1 AND id=$2`, [co, id])).rows[0]?.state);
const backdate = (ids) => systemTx(async (_c, t) =>
  t.query(`UPDATE ai_usage_attempts SET reserved_at = NOW() - INTERVAL '2 hours' WHERE id = ANY($1::bigint[])`, [ids]));

// Deterministic, company-scoped isolation. Resets ONLY the given disposable
// test company's usage/attempts/audit rows and budget limit; never touches
// another company, shared schema, or migration history.
const resetCompany = async (co, limit) => {
  await systemTx(async (_c, t) => {
    await t.query(`DELETE FROM ai_budget_usage WHERE company_id=$1`, [co]);
    await t.query(`DELETE FROM ai_usage_attempts WHERE company_id=$1`, [co]);
    await t.query(`DELETE FROM ai_audit_logs WHERE company_id=$1`, [co]);
    await t.query(
      `INSERT INTO ai_budgets (company_id, monthly_token_limit) VALUES ($1,$2)
       ON CONFLICT (company_id) DO UPDATE SET monthly_token_limit=EXCLUDED.monthly_token_limit`,
      [co, limit]
    );
  });
};

const results = [];
const check = (n, ok, d) => results.push({ n, ok: !!ok, d });

await systemTx(async (_c, t) => {
  await t.query(`INSERT INTO companies (id) VALUES ($1),($2) ON CONFLICT DO NOTHING`, [A, B]);
  await t.query(
    `INSERT INTO ai_budgets (company_id, monthly_token_limit) VALUES ($1,$2),($3,$2)
     ON CONFLICT (company_id) DO UPDATE SET monthly_token_limit=EXCLUDED.monthly_token_limit`,
    [A, LIMIT, B]
  );
});

// 10) Concurrent recovery-identity provisioning (fresh users table).
let sysId = 0;
{
  await systemTx(async (_c, t) => t.query(`DELETE FROM users WHERE username='system-recovery'`));
  const settled = await Promise.allSettled(
    Array.from({ length: 12 }, () => svc.getSystemRecoveryUserId(makeDb()))
  );
  const fulfilled = settled.filter((s) => s.status === 'fulfilled');
  const ids = new Set(fulfilled.map((s) => Number(s.value)));
  const usersRow = await systemTx(async (_c, t) =>
    (await t.query(`SELECT COUNT(*)::text AS cnt FROM users WHERE username='system-recovery'`)).rows[0].cnt);
  sysId = ids.size === 1 ? [...ids][0] : 0;
  check('10. 12 concurrent provisioning → one canonical id', fulfilled.length === 12 && ids.size === 1 && usersRow === '1',
    { fulfilled: fulfilled.length, distinctIds: ids.size, users: usersRow });
}

// 1) Two racing reservations for the final tokens: exactly one succeeds.
await resetCompany(A, 1300);
{
  const r = await Promise.allSettled([
    companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs)),
    companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs)),
  ]);
  const ok = r.filter((x) => x.status === 'fulfilled').length;
  check('1. final-token race → exactly one', ok === 1, { ok });
}
// 2) 20 concurrent ≤ limit.
await resetCompany(A, LIMIT);
{
  const r = await Promise.allSettled(Array.from({ length: 20 }, () =>
    companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs))));
  const ok = r.filter((x) => x.status === 'fulfilled').length;
  const c = await counters(A);
  check('2. 20 concurrent ≤ limit', Number(c.reserved_tokens) <= LIMIT && ok * estimate <= LIMIT, { ok, reserved: c.reserved_tokens });
}
// 3) Duplicate settlement counted once.
await resetCompany(A, 1_000_000);
let attemptId = 0;
await companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs)).then((x) => { attemptId = x.attemptId; });
{
  const before = Number((await counters(A)).settled_tokens);
  await Promise.allSettled(Array.from({ length: 8 }, () =>
    companyTx(A, (_c, t) => svc.settleAttempt(t, A, attemptId, { totalTokens: 300 }))));
  const after = Number((await counters(A)).settled_tokens);
  check('3. duplicate settlement once', after - before === 300, { before, after });
}
// 4) Settlement vs definite release (one terminal outcome).
{
  await resetCompany(A, 1_000_000);
  const a = await companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs));
  await Promise.allSettled([
    companyTx(A, (_c, t) => svc.settleAttempt(t, A, a.attemptId, { totalTokens: 200 })),
    companyTx(A, (_c, t) => svc.recordProviderFailure(t, A, a.attemptId, false, '4xx')),
  ]);
  const st = await attemptState(A, a.attemptId);
  check('4. settle vs release → one terminal', st === 'settled' || st === 'released', { st });
}
// 5) Settlement vs unresolved recovery (one transition).
{
  await resetCompany(A, 1_000_000);
  const a = await companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs));
  await backdate([a.attemptId]);
  await Promise.allSettled([
    companyTx(A, (_c, t) => svc.settleAttempt(t, A, a.attemptId, { totalTokens: 100 })),
    companyTx(A, (_c, t) => svc.recoverUnresolvedAttempts(t, A, sysId)),
  ]);
  const st = await attemptState(A, a.attemptId);
  check('5. settle vs recovery → one transition', st === 'settled' || st === 'unresolved', { st });
}
// 6) Two recovery workers over the same stale attempts: one transition + one audit row each.
{
  await resetCompany(A, 1_000_000);
  const ids = [];
  for (let i = 0; i < 5; i++) {
    const a = await companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs));
    ids.push(a.attemptId);
  }
  await backdate(ids);
  const auditBefore = await auditCount(A);
  const settled = await Promise.allSettled([
    companyTx(A, (_c, t) => svc.recoverUnresolvedAttempts(t, A, sysId)),
    companyTx(A, (_c, t) => svc.recoverUnresolvedAttempts(t, A, sysId)),
  ]);
  const recovered = settled.filter((s) => s.status === 'fulfilled').reduce((n, s) => n + Number(s.value), 0);
  const states = await systemTx(async (_c, t) =>
    (await t.query(`SELECT id, state FROM ai_usage_attempts WHERE id = ANY($1::bigint[])`, [ids])).rows);
  const allUnresolved = states.length === ids.length && states.every((r) => r.state === 'unresolved');
  const auditAfter = await auditCount(A);
  check('6. two recovery workers → one transition + one audit each',
    recovered === ids.length && allUnresolved && auditAfter - auditBefore === ids.length,
    { recovered, allUnresolved, auditDelta: auditAfter - auditBefore });
}
// 7) Recovery must not touch a recent (non-stale) active invocation.
{
  await resetCompany(A, 1_000_000);
  const a = await companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs));
  const beforeReserved = Number((await counters(A)).reserved_tokens);
  const recovered = await companyTx(A, (_c, t) => svc.recoverUnresolvedAttempts(t, A, sysId));
  const st = await attemptState(A, a.attemptId);
  const afterReserved = Number((await counters(A)).reserved_tokens);
  check('7. recovery vs live invocation → untouched',
    recovered === 0 && st === 'reserved' && beforeReserved === afterReserved,
    { recovered, st, beforeReserved, afterReserved });
}
// 8) Two scheduler instances (recoverAllUnresolved) must not duplicate transitions/audits.
{
  await resetCompany(A, 1_000_000);
  const ids = [];
  for (let i = 0; i < 4; i++) {
    const a = await companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs));
    ids.push(a.attemptId);
  }
  await backdate(ids);
  const auditBefore = await auditCount(A);
  const settled = await Promise.allSettled([
    svc.recoverAllUnresolved(makeDb()),
    svc.recoverAllUnresolved(makeDb()),
  ]);
  const fulfilled = settled.filter((s) => s.status === 'fulfilled').map((s) => s.value);
  const recovered = fulfilled.reduce((n, r) => n + Number(r.recovered), 0);
  const failed = fulfilled.reduce((n, r) => n + Number(r.failed), 0);
  const states = await systemTx(async (_c, t) =>
    (await t.query(`SELECT id, state FROM ai_usage_attempts WHERE id = ANY($1::bigint[])`, [ids])).rows);
  const allUnresolved = states.length === ids.length && states.every((r) => r.state === 'unresolved');
  const auditAfter = await auditCount(A);
  check('8. two schedulers → no duplicate transitions/audits',
    recovered === ids.length && allUnresolved && auditAfter - auditBefore === ids.length && failed === 0,
    { recovered, allUnresolved, auditDelta: auditAfter - auditBefore, failed });
}
// 9) Two-company isolation.
{
  await resetCompany(A, 1_000_000);
  await resetCompany(B, 1_000_000);
  const bBefore = await counters(B);
  await companyTx(A, (_c, t) => svc.reserveAttempt(t, A, crypto.randomUUID(), 1, 'p', 'm', msgs));
  const bAfter = await counters(B);
  check('9. company isolation', Number(bAfter.reserved_tokens) === Number(bBefore.reserved_tokens), { bBefore, bAfter });
}

await pool.end();
let ok = 0;
for (const r of results) { console.log(`  [${r.ok ? 'PASS' : 'FAIL'}] ${r.n}`, JSON.stringify(r.d)); if (r.ok) ok++; }
console.log(`\nPostgreSQL service-level concurrency: ${ok}/${results.length} passed`);
process.exit(ok === results.length ? 0 : 1);
