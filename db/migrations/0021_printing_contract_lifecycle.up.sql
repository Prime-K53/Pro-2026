-- 2. Customer acceptance records
CREATE TABLE contract_acceptances (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  contract_id       BIGINT NOT NULL,
  method            VARCHAR(16) NOT NULL CHECK (method IN ('drawn','otp','upload')),
  signer_name       VARCHAR(200) NOT NULL,
  signer_email      VARCHAR(200),
  signer_phone      VARCHAR(40),
  document_version  VARCHAR(40) NOT NULL,
  evidence_file_id  BIGINT,
  otp_verified_at   TIMESTAMPTZ,
  accepted_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ip_address        VARCHAR(64),
  outcome           VARCHAR(16) NOT NULL CHECK (outcome IN ('accepted','rejected')),
  created_by        BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_contract_acceptances_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_contract_acceptances_contract FOREIGN KEY (company_id, contract_id)
    REFERENCES printing_contracts (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_contract_acceptances_evidence FOREIGN KEY (company_id, evidence_file_id)
    REFERENCES stored_files (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_contract_acceptances_contract
  ON contract_acceptances (company_id, contract_id, accepted_at DESC);

ALTER TABLE contract_acceptances ENABLE ROW LEVEL SECURITY;
ALTER TABLE contract_acceptances FORCE ROW LEVEL SECURITY;
CREATE POLICY p_contract_acceptances_isolation ON contract_acceptances
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 3. Renewal predecessor + acceptance FKs
ALTER TABLE printing_contracts
  DROP CONSTRAINT IF EXISTS fk_printing_contracts_renewal_of;
ALTER TABLE printing_contracts
  ADD CONSTRAINT fk_printing_contracts_renewal_of
  FOREIGN KEY (company_id, renewal_of_contract_id)
  REFERENCES printing_contracts (company_id, id) ON DELETE RESTRICT;

ALTER TABLE printing_contracts
  DROP CONSTRAINT IF EXISTS fk_printing_contracts_acceptance;
ALTER TABLE printing_contracts
  ADD CONSTRAINT fk_printing_contracts_acceptance
  FOREIGN KEY (company_id, customer_acceptance_id)
  REFERENCES contract_acceptances (company_id, id) ON DELETE RESTRICT;

ALTER TABLE printing_contracts
  DROP CONSTRAINT IF EXISTS fk_printing_contracts_settlement_journal;
ALTER TABLE printing_contracts
  ADD CONSTRAINT fk_printing_contracts_settlement_journal
  FOREIGN KEY (company_id, settlement_journal_txn_id)
  REFERENCES journal_transactions (company_id, id) ON DELETE RESTRICT;

ALTER TABLE printing_contracts
  DROP CONSTRAINT IF EXISTS ck_printing_contracts_settlement_mode;
ALTER TABLE printing_contracts
  ADD CONSTRAINT ck_printing_contracts_settlement_mode
  CHECK (settlement_mode IS NULL OR settlement_mode IN ('refund','forfeit'));

ALTER TABLE printing_contracts
  DROP CONSTRAINT IF EXISTS ck_printing_contracts_settled_amount;
ALTER TABLE printing_contracts
  ADD CONSTRAINT ck_printing_contracts_settled_amount
  CHECK (settled_amount >= 0);

ALTER TABLE printing_contracts
  DROP CONSTRAINT IF EXISTS ck_printing_contracts_settlement;
ALTER TABLE printing_contracts
  ADD CONSTRAINT ck_printing_contracts_settlement CHECK (
    settlement_mode IS NULL
    OR (
      settlement_mode IN ('refund','forfeit')
      AND settled_amount > 0
      AND settlement_journal_txn_id IS NOT NULL
    )
  );

-- 4. Metadata backfill (non-financial)
UPDATE printing_contracts
   SET activated_at = created_at
 WHERE status IN ('active','exhausted','cancelled')
   AND activated_at IS NULL;

UPDATE printing_contracts
   SET cancelled_at = updated_at
 WHERE status = 'cancelled'
   AND cancelled_at IS NULL;

-- 5. Status CHECK expansion
ALTER TABLE printing_contracts
  DROP CONSTRAINT IF EXISTS printing_contracts_status_check;

ALTER TABLE printing_contracts
  ADD CONSTRAINT printing_contracts_status_check
  CHECK (status IN ('draft','active','suspended','completed','exhausted','cancelled'));

-- 6. Lifecycle metadata consistency
ALTER TABLE printing_contracts
  DROP CONSTRAINT IF EXISTS ck_printing_contracts_lifecycle_meta;
ALTER TABLE printing_contracts
  ADD CONSTRAINT ck_printing_contracts_lifecycle_meta CHECK (
    (status <> 'active' OR activated_at IS NOT NULL)
    AND (status <> 'completed' OR completed_at IS NOT NULL)
    AND (status <> 'suspended' OR suspended_at IS NOT NULL)
    AND (status <> 'cancelled' OR cancelled_at IS NOT NULL)
  );

