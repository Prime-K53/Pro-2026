-- 4. Scheduled Report Delivery
-- ============================================================================
CREATE TABLE IF NOT EXISTS report_schedules (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  name           VARCHAR(160) NOT NULL,
  report_key     VARCHAR(64) NOT NULL,
  frequency      VARCHAR(16) NOT NULL DEFAULT 'monthly'
                   CHECK (frequency IN ('daily', 'weekly', 'monthly', 'quarterly')),
  day_of_week    SMALLINT CHECK (day_of_week IS NULL OR day_of_week BETWEEN 0 AND 6),
  day_of_month   SMALLINT CHECK (day_of_month IS NULL OR day_of_month BETWEEN 1 AND 28),
  time_of_day    TIME NOT NULL DEFAULT '07:00',
  recipients     TEXT[] NOT NULL DEFAULT '{}',
  filters_json   JSONB NOT NULL DEFAULT '{}'::JSONB,
  is_active      BOOLEAN NOT NULL DEFAULT TRUE,
  last_run_at    TIMESTAMPTZ,
  next_run_at    TIMESTAMPTZ NOT NULL,
  created_by     BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_report_schedules_company_id UNIQUE (company_id, id)
);

CREATE INDEX IF NOT EXISTS ix_report_schedules_due
  ON report_schedules (company_id, is_active, next_run_at);

