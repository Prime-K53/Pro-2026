-- Migration 0013: Finance Controls, Period Close Checklist & Operational Reporting Foundation
-- Adds:
--   - Maker-checker approval policies and approval requests (threshold based)
--   - Fiscal period close checklist with auto evidence + manual sign-off tasks
--   - Scheduled report delivery (recurring report runs + delivery log linkage)
--   - Indexes for control-room queues

-- ============================================================================
-- 1. Maker-Checker Approval Policies (per company, per action type)
-- ============================================================================
CREATE TABLE IF NOT EXISTS approval_policies (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  action_type       VARCHAR(32) NOT NULL CHECK (action_type IN (
                      'invoice', 'bill', 'customer_payment', 'bill_payment',
                      'journal_entry', 'credit_memo'
                    )),
  threshold_amount  NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (threshold_amount >= 0),
  is_enabled        BOOLEAN NOT NULL DEFAULT FALSE,
  require_note      BOOLEAN NOT NULL DEFAULT FALSE,
  created_by        BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_by        BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_approval_policies_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_approval_policies_company_action UNIQUE (company_id, action_type)
);

CREATE TRIGGER trg_approval_policies_updated_at
  BEFORE UPDATE ON approval_policies
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE approval_policies ENABLE ROW LEVEL SECURITY;
ALTER TABLE approval_policies FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS p_approval_policies_isolation ON approval_policies;
CREATE POLICY p_approval_policies_isolation ON approval_policies
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- ============================================================================
-- 2. Approval Requests (queue + payload snapshot for approved replay)
-- ============================================================================
CREATE TABLE IF NOT EXISTS approval_requests (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id       BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  action_type      VARCHAR(32) NOT NULL CHECK (action_type IN (
                     'invoice', 'bill', 'customer_payment', 'bill_payment',
                     'journal_entry', 'credit_memo'
                   )),
  entity_type      VARCHAR(40) NOT NULL,
  entity_id        BIGINT,
  business_date    DATE NOT NULL,
  amount           NUMERIC(19, 4) NOT NULL CHECK (amount >= 0),
  status           VARCHAR(16) NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
  requested_by     BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  requested_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  decided_by       BIGINT REFERENCES users(id) ON DELETE SET NULL,
  decided_at       TIMESTAMPTZ,
  decision_note    TEXT,
  payload_json     JSONB NOT NULL DEFAULT '{}'::JSONB,
  payload_hash     CHAR(64) NOT NULL,
  idempotency_key  VARCHAR(128),
  consumed_at      TIMESTAMPTZ,
  consumed_by      BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_approval_requests_company_id UNIQUE (company_id, id),
  CONSTRAINT ck_approval_requests_decision CHECK (
    (status = 'pending' AND decided_by IS NULL AND decided_at IS NULL)
    OR (status <> 'pending' AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_approval_requests_idem
  ON approval_requests (company_id, action_type, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_approval_requests_queue
  ON approval_requests (company_id, status, requested_at DESC);

CREATE INDEX IF NOT EXISTS ix_approval_requests_entity
  ON approval_requests (company_id, entity_type, entity_id);

CREATE TRIGGER trg_approval_requests_updated_at
  BEFORE UPDATE ON approval_requests
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE approval_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE approval_requests FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS p_approval_requests_isolation ON approval_requests;
CREATE POLICY p_approval_requests_isolation ON approval_requests
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- ============================================================================
-- 3. Fiscal Period Close Checklist
-- ============================================================================
CREATE TABLE IF NOT EXISTS fiscal_period_close_tasks (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  period_id      BIGINT NOT NULL,
  task_key       VARCHAR(64) NOT NULL,
  label          VARCHAR(200) NOT NULL,
  category       VARCHAR(32) NOT NULL DEFAULT 'financial',
  is_required    BOOLEAN NOT NULL DEFAULT TRUE,
  is_manual      BOOLEAN NOT NULL DEFAULT FALSE,
  status         VARCHAR(16) NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'complete', 'waived')),
  evidence_json  JSONB NOT NULL DEFAULT '{}'::JSONB,
  notes          TEXT,
  completed_by   BIGINT REFERENCES users(id) ON DELETE SET NULL,
  completed_at   TIMESTAMPTZ,
  sort_order     INTEGER NOT NULL DEFAULT 100,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_period_close_tasks_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_period_close_tasks_period_key UNIQUE (company_id, period_id, task_key),
  CONSTRAINT fk_period_close_tasks_period FOREIGN KEY (company_id, period_id)
    REFERENCES fiscal_periods (company_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_period_close_tasks_period
