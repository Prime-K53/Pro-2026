-- Prime ERP — V2 WS-4 R2: effective-dated salary structures.
--
-- A salary structure is the authoritative pay rate for an employee for a date
-- range. Payroll resolves the structure effective on the pay date and falls
-- back to the employee master rate only when no structure exists.

CREATE TABLE IF NOT EXISTS salary_structures (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  employee_id    BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  effective_from DATE NOT NULL,
  effective_to   DATE,
  pay_type       TEXT NOT NULL CHECK (pay_type IN ('salary', 'hourly')),
  pay_rate       NUMERIC(19,4) NOT NULL CHECK (pay_rate >= 0),
  pay_frequency  TEXT NOT NULL CHECK (pay_frequency IN ('weekly', 'biweekly', 'semimonthly', 'monthly')),
  currency       CHAR(3),
  notes          TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_salary_structures_company_id UNIQUE (company_id, id)
);

CREATE INDEX IF NOT EXISTS idx_salary_structures_company
  ON salary_structures (company_id, employee_id, effective_from);

ALTER TABLE salary_structures ENABLE ROW LEVEL SECURITY;
ALTER TABLE salary_structures FORCE ROW LEVEL SECURITY;
CREATE POLICY p_salary_structures_isolation ON salary_structures
  USING (company_id = app_current_company_id());