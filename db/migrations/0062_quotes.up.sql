-- Migration 0062: Versioned quote documents.
--
-- A formal, versioned quote for commercial work (estimate -> versioned quote ->
-- PO -> job), distinct from counter QuickPrint. Each quote owns an ordered
-- series of versions; every version is an immutable snapshot of its lines and
-- totals, so a revised quote keeps its full history.

CREATE TABLE IF NOT EXISTS quotes (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  quote_number   VARCHAR(64) NOT NULL,
  customer_id    BIGINT NOT NULL,
  title          VARCHAR(200) NOT NULL,
  status         VARCHAR(20) NOT NULL DEFAULT 'draft'
                   CHECK (status IN ('draft', 'sent', 'accepted', 'declined', 'expired', 'converted')),
  current_version INTEGER NOT NULL DEFAULT 1,
  total          NUMERIC(19, 4) NOT NULL DEFAULT 0,
  valid_until    DATE,
  notes          TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_quotes_company_number UNIQUE (company_id, quote_number),
  CONSTRAINT uq_quotes_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_quotes_customer FOREIGN KEY (company_id, customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT
);

ALTER TABLE quotes ENABLE ROW LEVEL SECURITY;
ALTER TABLE quotes FORCE ROW LEVEL SECURITY;
CREATE POLICY p_quotes_isolation ON quotes
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

CREATE TABLE IF NOT EXISTS quote_versions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  quote_id    BIGINT NOT NULL,
  version_no  INTEGER NOT NULL,
  lines       JSONB NOT NULL DEFAULT '[]'::JSONB,
  subtotal    NUMERIC(19, 4) NOT NULL DEFAULT 0,
  tax_amount  NUMERIC(19, 4) NOT NULL DEFAULT 0,
  total       NUMERIC(19, 4) NOT NULL DEFAULT 0,
  notes       TEXT,
  created_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_quote_versions_quote_no UNIQUE (quote_id, version_no),
  CONSTRAINT fk_quote_versions_quote FOREIGN KEY (company_id, quote_id)
    REFERENCES quotes (company_id, id) ON DELETE CASCADE
);

ALTER TABLE quote_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE quote_versions FORCE ROW LEVEL SECURITY;
CREATE POLICY p_quote_versions_isolation ON quote_versions
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));