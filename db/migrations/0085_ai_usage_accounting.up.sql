-- 0085_ai_usage_accounting
--
-- D-05 durable provider-attempt accounting + atomic budget reservations.
-- Per-company, per-UTC-calendar-month. Two tables:
--   ai_budget_usage  : atomic reserved/settled token counters (PK company+period)
--   ai_usage_attempts: one row per provider invocation (request_id + attempt_no)
-- Additive; RLS company-scoped; no change to existing migrations.

BEGIN;

CREATE TABLE ai_budget_usage (
  company_id      BIGINT NOT NULL,
  period          TEXT   NOT NULL,           -- 'YYYY-MM' (UTC)
  reserved_tokens BIGINT NOT NULL DEFAULT 0,
  settled_tokens  BIGINT NOT NULL DEFAULT 0,
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (company_id, period)
);

ALTER TABLE ai_budget_usage ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_budget_usage FORCE ROW LEVEL SECURITY;
CREATE POLICY ai_budget_usage_iso ON ai_budget_usage
  USING (company_id = app_current_company_id())
  WITH CHECK (company_id = app_current_company_id());

CREATE TABLE ai_usage_attempts (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id         BIGINT NOT NULL,
  request_id         UUID   NOT NULL,
  attempt_no         INT    NOT NULL,
  provider           TEXT   NOT NULL,
  model              TEXT,
  reservation_tokens INT    NOT NULL DEFAULT 0,
  state              TEXT   NOT NULL DEFAULT 'reserved',
  prompt_tokens      INT,
  completion_tokens  INT,
  total_tokens       INT,
  usage_source       TEXT,
  provider_request_id TEXT,
  error              TEXT,
  reserved_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  settled_at         TIMESTAMPTZ,
  CONSTRAINT ai_usage_attempts_request_attempt_uniq UNIQUE (request_id, attempt_no)
);

ALTER TABLE ai_usage_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_usage_attempts FORCE ROW LEVEL SECURITY;
CREATE POLICY ai_usage_attempts_iso ON ai_usage_attempts
  USING (company_id = app_current_company_id())
  WITH CHECK (company_id = app_current_company_id());

CREATE INDEX ai_usage_attempts_company_idx ON ai_usage_attempts (company_id, reserved_at);

COMMIT;