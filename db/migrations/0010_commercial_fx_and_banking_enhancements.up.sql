-- Migration 0010: Commercial, Foreign Exchange, PO-Bill Linkage & Banking Enhancements
-- Adds:
--   - Multi-currency exchange_rates table (RLS isolated) + FX fields on commercial documents
--   - Purchase order linkage on bills & bill_lines
--   - Bank transaction status/categorization/transfer pair columns & expanded txn_type
--   - Reconciliation reversal audit metadata
--   - Recurring invoice generation tracking & saved report run timestamps
--   - Expanded journal_transactions source_type constraint for all Phase 5 workflows

-- 1. Exchange Rates (Exact NUMERIC(19,6) FX rates per company)
CREATE TABLE IF NOT EXISTS exchange_rates (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  from_currency CHAR(3) NOT NULL,
  to_currency   CHAR(3) NOT NULL,
  rate_date     DATE NOT NULL,
  rate          NUMERIC(19, 6) NOT NULL CHECK (rate > 0),
  source        VARCHAR(60) NOT NULL DEFAULT 'manual',
  created_by    BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_exchange_rates_pair CHECK (from_currency <> to_currency)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_exchange_rates_company_pair_date
  ON exchange_rates (company_id, from_currency, to_currency, rate_date);

ALTER TABLE exchange_rates ENABLE ROW LEVEL SECURITY;
ALTER TABLE exchange_rates FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS p_exchange_rates_isolation ON exchange_rates;
CREATE POLICY p_exchange_rates_isolation ON exchange_rates
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

