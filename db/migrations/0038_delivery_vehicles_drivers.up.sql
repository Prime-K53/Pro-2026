-- 3. Delivery Schedules — scheduling for delivery notes.
CREATE TABLE IF NOT EXISTS delivery_schedules (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  delivery_note_id  BIGINT NOT NULL,
  scheduled_date    DATE NOT NULL,
  time_window       TEXT,
  assigned_driver_id BIGINT,
  assigned_vehicle_id BIGINT,
  status            TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'in_transit', 'delivered', 'failed')),
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
