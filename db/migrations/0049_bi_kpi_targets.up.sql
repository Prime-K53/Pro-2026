-- Prime ERP — V2 WS-8: BI KPI targets for variance analysis.

CREATE TABLE IF NOT EXISTS bi_kpi_targets (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  kpi_key        TEXT NOT NULL,
  target_value   NUMERIC(19,4) NOT NULL,
  period         TEXT NOT NULL DEFAULT 'monthly',
  effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_bi_kpi_targets UNIQUE (company_id, kpi_key, period, effective_from)
);

CREATE INDEX IF NOT EXISTS idx_bi_kpi_targets_company
  ON bi_kpi_targets (company_id, kpi_key);

ALTER TABLE bi_kpi_targets ENABLE ROW LEVEL SECURITY;
ALTER TABLE bi_kpi_targets FORCE ROW LEVEL SECURITY;
CREATE POLICY p_bi_kpi_targets_isolation ON bi_kpi_targets
  USING (company_id = app_current_company_id());