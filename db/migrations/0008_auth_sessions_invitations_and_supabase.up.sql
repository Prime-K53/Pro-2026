-- Migration 0008: Phase 3 Authentication, Revocable Sessions, Invitations & Password Recovery
-- Preserves SlowBooks-Pro-2026 revocable session_version, expiring accounts, one-time invites,
-- and bridges global Supabase Auth identities to isolated per-company memberships.

-- 1. Extend global users for Supabase Auth UID + password lifecycle
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS supabase_uid UUID,
  ADD COLUMN IF NOT EXISTS must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS last_password_change_at TIMESTAMPTZ;

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_supabase_uid
  ON users (supabase_uid)
  WHERE supabase_uid IS NOT NULL;

-- 2. Extend company_memberships for per-company version revocation & expiry
ALTER TABLE company_memberships
  ADD COLUMN IF NOT EXISTS membership_version INTEGER NOT NULL DEFAULT 0 CHECK (membership_version >= 0),
  ADD COLUMN IF NOT EXISTS expires_on DATE,
  ADD COLUMN IF NOT EXISTS invited_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS revoked_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS revoked_by BIGINT REFERENCES users(id) ON DELETE SET NULL;

-- 3. Company User Invitations (One-Time Token Flow)
CREATE TABLE user_invitations (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id          BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  email               VARCHAR(255) NOT NULL,
  username            VARCHAR(100) NOT NULL,
  display_name        VARCHAR(150) NOT NULL,
  role                VARCHAR(24) NOT NULL CHECK (role IN ('Administrator', 'Accountant', 'Bookkeeper', 'ProductionManager', 'Read-Only')),
  token_hash          CHAR(64) NOT NULL,
  invited_by          BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  expires_on          DATE,
  invite_expires_at   TIMESTAMPTZ NOT NULL,
  status              VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'revoked', 'expired')),
  accepted_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  accepted_at         TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_user_invitations_token UNIQUE (token_hash),
  CONSTRAINT uq_user_invitations_company_id UNIQUE (company_id, id)
);

CREATE INDEX ix_user_invitations_company_status ON user_invitations (company_id, status, created_at DESC);

ALTER TABLE user_invitations ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_invitations FORCE ROW LEVEL SECURITY;
CREATE POLICY p_user_invitations_isolation ON user_invitations
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 4. Server-Side Revocable Sessions (Bound to User + Active Company + Membership Versions)
CREATE TABLE auth_sessions (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_token_hash   CHAR(64) NOT NULL,
  user_id              BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  active_company_id    BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  membership_id        BIGINT NOT NULL,
  user_session_version INTEGER NOT NULL,
  membership_version   INTEGER NOT NULL,
  supabase_sub         UUID,
  ip_address           VARCHAR(64),
  user_agent           TEXT,
  issued_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_seen_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at           TIMESTAMPTZ NOT NULL,
  revoked_at           TIMESTAMPTZ,
  revoke_reason        VARCHAR(100),
  CONSTRAINT uq_auth_sessions_token_hash UNIQUE (session_token_hash),
  CONSTRAINT fk_auth_sessions_membership FOREIGN KEY (active_company_id, membership_id)
    REFERENCES company_memberships (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT ck_auth_sessions_expiry CHECK (expires_at > issued_at)
);

CREATE INDEX ix_auth_sessions_user_active ON auth_sessions (user_id, revoked_at, expires_at DESC);

-- 5. Password Recovery Tokens (Auditable recovery alongside Supabase Auth)
CREATE TABLE password_recovery_tokens (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  email            VARCHAR(255) NOT NULL,
  token_hash       CHAR(64) NOT NULL,
  delivery_channel VARCHAR(32) NOT NULL DEFAULT 'supabase_recovery' CHECK (delivery_channel IN ('supabase_recovery', 'local_token')),
  expires_at       TIMESTAMPTZ NOT NULL,
  used_at          TIMESTAMPTZ,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_password_recovery_token_hash UNIQUE (token_hash)
);

-- Ensure least-privilege runtime role has table/sequence access across all objects
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO pms_app_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO pms_app_role;
