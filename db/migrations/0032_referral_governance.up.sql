CREATE TABLE IF NOT EXISTS discount_budgets (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  budget_type TEXT NOT NULL CHECK (budget_type IN ('referral_discount', 'cashback', 'commission', 'promotion', 'discount_budget', 'other')),
  name        TEXT NOT NULL,
  allocated   NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (allocated >= 0),
  consumed    NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (consumed >= 0),
  currency    CHAR(3) NOT NULL DEFAULT 'ZWG',
  status      TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'frozen', 'exhausted', 'archived')),
  start_date  DATE,
  end_date    DATE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
