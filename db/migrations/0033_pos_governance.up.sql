-- Migration 0033: POS Governance — Shifts, Suspended Sales, Split Payments, Barcode, Reconciliation.
--
-- Adds Phase 1 POS completion: shift management, drawer reconciliation, suspended sales,
-- split payments, barcode tracking, and stock concurrency protection.

-- 1. POS Shifts — shift open/close, drawer float, cash reconciliation.
CREATE TABLE IF NOT EXISTS pos_shifts (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  cashier_id   BIGINT NOT NULL REFERENCES users(id),
  opened_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  closed_at    TIMESTAMPTZ,
  opening_float NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (opening_float >= 0),
  closing_float NUMERIC(12,2) CHECK (closing_float >= 0),
  cash_in      NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (cash_in >= 0),
  cash_out     NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (cash_out >= 0),
  expected_cash NUMERIC(12,2),
  actual_cash  NUMERIC(12,2),
  variance     NUMERIC(12,2),
  status       TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  notes        TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_pos_shifts_company_id UNIQUE (company_id, id)
);

CREATE INDEX idx_pos_shifts_company ON pos_shifts (company_id);
CREATE INDEX idx_pos_shifts_cashier ON pos_shifts (company_id, cashier_id);
CREATE INDEX idx_pos_shifts_status ON pos_shifts (company_id, status);

CREATE TRIGGER trg_pos_shifts_updated_at
  BEFORE UPDATE ON pos_shifts
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE pos_shifts ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos_shifts FORCE ROW LEVEL SECURITY;
CREATE POLICY p_pos_shifts_isolation ON pos_shifts
  USING (company_id = app_current_company_id());

-- 2. POS Suspended Sales — park and resume orders.
CREATE TABLE IF NOT EXISTS pos_suspended_sales (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  shift_id     BIGINT NOT NULL,
  pos_order_id BIGINT NOT NULL,
  suspended_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resumed_at   TIMESTAMPTZ,
  status       TEXT NOT NULL DEFAULT 'suspended' CHECK (status IN ('suspended', 'resumed')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_pos_suspended_sales_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_pos_suspended_sales_shift FOREIGN KEY (company_id, shift_id)
    REFERENCES pos_shifts (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX idx_pos_suspended_sales_company ON pos_suspended_sales (company_id);
CREATE INDEX idx_pos_suspended_sales_shift ON pos_suspended_sales (company_id, shift_id);

ALTER TABLE pos_suspended_sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos_suspended_sales FORCE ROW LEVEL SECURITY;
CREATE POLICY p_pos_suspended_sales_isolation ON pos_suspended_sales
  USING (company_id = app_current_company_id());

-- 3. POS Transactions — split payment support.
CREATE TABLE IF NOT EXISTS pos_transactions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  shift_id     BIGINT NOT NULL,
  order_id     BIGINT NOT NULL,
  tender_type  TEXT NOT NULL CHECK (tender_type IN ('cash', 'card', 'mobile_money', 'bank_transfer', 'cheque', 'other')),
  amount       NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  tendered     NUMERIC(12,2) NOT NULL CHECK (tendered >= 0),
  change       NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (change >= 0),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_pos_transactions_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_pos_transactions_shift FOREIGN KEY (company_id, shift_id)
    REFERENCES pos_shifts (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX idx_pos_transactions_company ON pos_transactions (company_id);
CREATE INDEX idx_pos_transactions_shift ON pos_transactions (company_id, shift_id);
CREATE INDEX idx_pos_transactions_order ON pos_transactions (company_id, order_id);

ALTER TABLE pos_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos_transactions FORCE ROW LEVEL SECURITY;
CREATE POLICY p_pos_transactions_isolation ON pos_transactions
  USING (company_id = app_current_company_id());

-- 4. Barcode column on inventory_items — unique per company.
ALTER TABLE inventory_items ADD COLUMN IF NOT EXISTS barcode TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS uq_inventory_items_company_barcode
  ON inventory_items (company_id, barcode) WHERE barcode IS NOT NULL;

-- 5. Shift-level audit trail.
CREATE TABLE IF NOT EXISTS pos_shift_audit (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  shift_id     BIGINT NOT NULL,
  action       TEXT NOT NULL CHECK (action IN ('opened', 'closed', 'cash_in', 'cash_out', 'suspended', 'resumed', 'reconciled')),
  performed_by BIGINT NOT NULL REFERENCES users(id),
  performed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  details      JSONB,
  CONSTRAINT uq_pos_shift_audit_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_pos_shift_audit_shift FOREIGN KEY (company_id, shift_id)
    REFERENCES pos_shifts (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX idx_pos_shift_audit_company ON pos_shift_audit (company_id);
CREATE INDEX idx_pos_shift_audit_shift ON pos_shift_audit (company_id, shift_id);

ALTER TABLE pos_shift_audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos_shift_audit FORCE ROW LEVEL SECURITY;
CREATE POLICY p_pos_shift_audit_isolation ON pos_shift_audit
  USING (company_id = app_current_company_id());

-- 6. Add shift_id to pos_orders for shift tracking.
ALTER TABLE pos_orders ADD COLUMN IF NOT EXISTS shift_id BIGINT;

-- 7. Add index for shift queries on pos_orders.
CREATE INDEX IF NOT EXISTS idx_pos_orders_shift ON pos_orders (company_id, shift_id, created_at DESC);