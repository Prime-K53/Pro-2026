-- Prime ERP — V2 WS-7: outbound message log and idempotent delivery receipts.

CREATE TABLE IF NOT EXISTS communications_messages (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id          BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  channel             TEXT NOT NULL CHECK (channel IN ('sms', 'whatsapp', 'email')),
  recipient           TEXT NOT NULL,
  body                TEXT NOT NULL,
  status              TEXT NOT NULL DEFAULT 'queued'
                      CHECK (status IN ('queued', 'sent', 'delivered', 'failed', 'undelivered')),
  provider            TEXT,
  provider_message_id TEXT,
  error               TEXT,
  sent_at             TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_comms_provider_message
  ON communications_messages (company_id, provider_message_id)
  WHERE provider_message_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_comms_messages_company
  ON communications_messages (company_id, created_at DESC);

ALTER TABLE communications_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE communications_messages FORCE ROW LEVEL SECURITY;
CREATE POLICY p_comms_messages_isolation ON communications_messages
  USING (company_id = app_current_company_id());