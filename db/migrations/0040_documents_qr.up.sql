-- Migration 0040: Documents — QR Verification.
--
-- Adds Phase 8 QR verification: cryptographic tokens for document authenticity.

CREATE TABLE IF NOT EXISTS document_qr_codes (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  document_kind TEXT NOT NULL,
  document_id   BIGINT NOT NULL,
  qr_token_hash TEXT NOT NULL UNIQUE,
  qr_token_salt TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  revoked_at    TIMESTAMPTZ,
  CONSTRAINT uq_document_qr_codes_company_id UNIQUE (company_id, id)
);

CREATE INDEX idx_document_qr_codes_company ON document_qr_codes (company_id);
CREATE INDEX idx_document_qr_codes_document ON document_qr_codes (company_id, document_kind, document_id);
CREATE INDEX idx_document_qr_codes_token ON document_qr_codes (qr_token_hash);

ALTER TABLE document_qr_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_qr_codes FORCE ROW LEVEL SECURITY;
CREATE POLICY p_document_qr_codes_isolation ON document_qr_codes
  USING (company_id = app_current_company_id());