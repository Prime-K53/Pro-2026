-- Migration 0022: Printing Contract Amendments
-- Adds versioned, approval-gated contract amendments. Historical posted
-- financial transactions are never modified; amendments apply to future,
-- uncompleted work only.

CREATE TABLE contract_amendments (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  contract_id     BIGINT NOT NULL,
  version         INTEGER NOT NULL CHECK (version > 0),
  amendment_type  VARCHAR(16) NOT NULL
                  CHECK (amendment_type IN ('terms','schedule','amount')),
  reason          TEXT NOT NULL,
  old_values      JSONB NOT NULL,
  new_values      JSONB NOT NULL,
  status          VARCHAR(20) NOT NULL DEFAULT 'pending_acceptance'
                  CHECK (status IN ('pending_acceptance','effective','rejected')),
  requested_by    BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  approved_by     BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  approved_at     TIMESTAMPTZ,
  acceptance_id   BIGINT,
  effective_at    TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_contract_amendments_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_contract_amendments_version UNIQUE (company_id, contract_id, version),
  CONSTRAINT fk_contract_amendments_contract FOREIGN KEY (company_id, contract_id)
    REFERENCES printing_contracts (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_contract_amendments_acceptance FOREIGN KEY (company_id, acceptance_id)
    REFERENCES contract_acceptances (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT ck_contract_amendments_approval CHECK (
    status <> 'effective'
    OR (approved_by IS NOT NULL AND approved_at IS NOT NULL AND effective_at IS NOT NULL)
  )
);

CREATE INDEX ix_contract_amendments_contract
  ON contract_amendments (company_id, contract_id, version DESC);

ALTER TABLE contract_amendments ENABLE ROW LEVEL SECURITY;
ALTER TABLE contract_amendments FORCE ROW LEVEL SECURITY;
CREATE POLICY p_contract_amendments_isolation ON contract_amendments
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

CREATE TRIGGER trg_contract_amendments_updated_at
  BEFORE UPDATE ON contract_amendments
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

