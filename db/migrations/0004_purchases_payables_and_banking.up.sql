-- Enforces composite multi-company isolation, unique vendor bill numbers, and bank reconciliation integrity.

-- 1. Vendors / Suppliers
CREATE TABLE vendors (
  id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id                 BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  name                       VARCHAR(200) NOT NULL,
  company_name               VARCHAR(200) NOT NULL,
  email                      VARCHAR(255),
  phone                      VARCHAR(50),
  address                    TEXT,
  ein_or_ssn                 VARCHAR(40),
  is_1099_eligible           BOOLEAN NOT NULL DEFAULT FALSE,
  default_expense_account_id BIGINT,
  payment_term_id            BIGINT,
  terms_label                VARCHAR(60) NOT NULL DEFAULT 'Net 30',
  balance                    NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  is_active                  BOOLEAN NOT NULL DEFAULT TRUE,
  created_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_vendors_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_vendors_default_acct FOREIGN KEY (company_id, default_expense_account_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_vendors_payment_term FOREIGN KEY (company_id, payment_term_id)
    REFERENCES payment_terms (company_id, id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_vendors_company_name_lower ON vendors (company_id, LOWER(name));

CREATE TRIGGER trg_vendors_updated_at
  BEFORE UPDATE ON vendors
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE vendors ENABLE ROW LEVEL SECURITY;
ALTER TABLE vendors FORCE ROW LEVEL SECURITY;
CREATE POLICY p_vendors_isolation ON vendors
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

