-- Migration 0003: Customers, Sales, Estimates, Invoices, Payments, Credit Memos & Receivables
-- Preserves SlowBooks-Pro-2026 entities while enforcing composite company isolation,
-- exact NUMERIC(19,4) monetary precision, and cost/profit tracking fields.

-- 1. Customers
CREATE TABLE customers (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  parent_customer_id BIGINT,
  customer_type     VARCHAR(24) NOT NULL DEFAULT 'corporate' CHECK (customer_type IN ('school', 'corporate', 'individual', 'government', 'nonprofit')),
  name              VARCHAR(200) NOT NULL,
  company_name      VARCHAR(200) NOT NULL,
  email             VARCHAR(255),
  phone             VARCHAR(50),
  billing_address   TEXT,
  shipping_address  TEXT,
  payment_term_id   BIGINT,
  terms_label       VARCHAR(60) NOT NULL DEFAULT 'Net 30',
  credit_limit      NUMERIC(19, 4) CHECK (credit_limit IS NULL OR credit_limit >= 0),
  balance           NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  is_tax_exempt     BOOLEAN NOT NULL DEFAULT FALSE,
  notes             TEXT,
  is_active         BOOLEAN NOT NULL DEFAULT TRUE,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_customers_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_customers_parent FOREIGN KEY (company_id, parent_customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_customers_payment_term FOREIGN KEY (company_id, payment_term_id)
    REFERENCES payment_terms (company_id, id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_customers_company_name_lower ON customers (company_id, LOWER(name));
CREATE INDEX ix_customers_company_type ON customers (company_id, customer_type, is_active);

CREATE TRIGGER trg_customers_updated_at
  BEFORE UPDATE ON customers
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE customers FORCE ROW LEVEL SECURITY;
CREATE POLICY p_customers_isolation ON customers
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

