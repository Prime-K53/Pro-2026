-- 5. Invoices (Accounts Receivable)
CREATE TABLE invoices (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  invoice_number  VARCHAR(64) NOT NULL,
  customer_id     BIGINT NOT NULL,
  invoice_date    DATE NOT NULL,
  due_date        DATE NOT NULL,
  payment_term_id BIGINT,
  terms_label     VARCHAR(60) NOT NULL DEFAULT 'Net 30',
  po_number       VARCHAR(80),
  status          VARCHAR(20) NOT NULL DEFAULT 'sent' CHECK (status IN ('draft', 'sent', 'partial', 'paid', 'overdue', 'voided')),
  is_sales_receipt BOOLEAN NOT NULL DEFAULT FALSE,
  is_tax_exempt   BOOLEAN NOT NULL DEFAULT FALSE,
  subtotal        NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (subtotal >= 0),
  tax_rate        NUMERIC(9, 6) NOT NULL DEFAULT 0.000000 CHECK (tax_rate >= 0 AND tax_rate <= 100),
  tax_amount      NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (tax_amount >= 0),
  total           NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (total >= 0),
  total_cost      NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (total_cost >= 0),
  gross_profit    NUMERIC(19, 4) GENERATED ALWAYS AS (subtotal - total_cost) STORED,
  amount_paid     NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (amount_paid >= 0),
  balance_due     NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (balance_due >= 0),
  journal_txn_id  BIGINT,
  source_estimate_id BIGINT,
  class_id        BIGINT,
  notes           TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_invoices_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_invoices_company_number UNIQUE (company_id, invoice_number),
  CONSTRAINT fk_invoices_customer FOREIGN KEY (company_id, customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_invoices_payment_term FOREIGN KEY (company_id, payment_term_id)
    REFERENCES payment_terms (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_invoices_journal FOREIGN KEY (company_id, journal_txn_id)
    REFERENCES journal_transactions (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_invoices_estimate FOREIGN KEY (company_id, source_estimate_id)
    REFERENCES estimates (company_id, id) ON DELETE SET NULL,
  CONSTRAINT fk_invoices_class FOREIGN KEY (company_id, class_id)
    REFERENCES txn_classes (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT ck_invoices_due_after_date CHECK (due_date >= invoice_date),
  CONSTRAINT ck_invoices_total_math CHECK (total = subtotal + tax_amount),
  CONSTRAINT ck_invoices_balance_math CHECK (amount_paid + balance_due = total)
);

CREATE INDEX ix_invoices_company_customer_status ON invoices (company_id, customer_id, status);
CREATE INDEX ix_invoices_company_due_date ON invoices (company_id, due_date) WHERE balance_due > 0;

