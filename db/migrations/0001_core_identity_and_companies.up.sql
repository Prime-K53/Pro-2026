  legal_name             VARCHAR(250) NOT NULL,
  tax_id_ein             VARCHAR(40),
  address                TEXT,
  city_state_zip         VARCHAR(200),
  phone                  VARCHAR(50),
  email                  VARCHAR(255),
  website                VARCHAR(255),
  base_currency          CHAR(3) NOT NULL DEFAULT 'ZMW',
  currency_symbol        VARCHAR(8) NOT NULL DEFAULT 'K',
  fiscal_year_start_month SMALLINT NOT NULL DEFAULT 1 CHECK (fiscal_year_start_month BETWEEN 1 AND 12),
  accounting_method      VARCHAR(12) NOT NULL DEFAULT 'accrual' CHECK (accounting_method IN ('accrual', 'cash')),
  sales_tax_rate         NUMERIC(9, 6) NOT NULL DEFAULT 0.000000 CHECK (sales_tax_rate >= 0 AND sales_tax_rate <= 100),
  rounding_mode          VARCHAR(20) NOT NULL DEFAULT 'HALF_EVEN' CHECK (rounding_mode IN ('HALF_EVEN', 'HALF_UP')),
