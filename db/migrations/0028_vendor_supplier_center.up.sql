-- Migration 0028: Vendor & Supplier Center Upgrade
-- Supplier-specific AP controls:
--   * governed vendor master (code, status, currency, category, bank details)
--   * traceable supplier opening balances posted to opening equity / AP
--   * archived supplier statements with delivery metadata
--   * approval action types for vendor governance and bank-detail changes
-- Supplier status semantics:
--   active   - normal purchasing and payment activity
--   inactive - no new POs, bills, or payments (historical records retained)
--   on_hold  - bills/POs may be recorded, but payments require release
--   blocked  - no new POs, bills, or payments until released

-- 1. Vendor master additions
ALTER TABLE vendors
  ADD COLUMN IF NOT EXISTS vendor_code VARCHAR(20),
  ADD COLUMN IF NOT EXISTS status VARCHAR(16) NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'inactive', 'on_hold', 'blocked')),
  ADD COLUMN IF NOT EXISTS currency_code CHAR(3) NOT NULL DEFAULT 'ZMW',
  ADD COLUMN IF NOT EXISTS opening_balance_bill_id BIGINT,
  ADD COLUMN IF NOT EXISTS notes TEXT,
  ADD COLUMN IF NOT EXISTS vendor_category VARCHAR(30) NOT NULL DEFAULT 'goods'
    CHECK (vendor_category IN ('goods', 'services', 'logistics', 'utilities', 'contractor', 'other')),
  ADD COLUMN IF NOT EXISTS is_preferred BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS bank_name VARCHAR(150),
  ADD COLUMN IF NOT EXISTS bank_account_name VARCHAR(150),
  ADD COLUMN IF NOT EXISTS bank_account_number VARCHAR(60),
  ADD COLUMN IF NOT EXISTS bank_branch VARCHAR(150);

-- Existing vendors inherit the company base currency instead of the column default.
UPDATE vendors v
   SET currency_code = co.base_currency
  FROM companies co
 WHERE co.id = v.company_id
   AND v.currency_code = 'ZMW';

-- Give legacy vendors stable supplier codes before the unique index is created.
WITH numbered AS (
  SELECT id, ROW_NUMBER() OVER (PARTITION BY company_id ORDER BY id) AS rn
    FROM vendors
   WHERE vendor_code IS NULL OR BTRIM(vendor_code) = ''
)
UPDATE vendors v
   SET vendor_code = 'SUP-' || LPAD(n.rn::TEXT, 6, '0')
  FROM numbered n
 WHERE v.id = n.id;

CREATE UNIQUE INDEX IF NOT EXISTS uq_vendors_company_code
  ON vendors (company_id, vendor_code)
  WHERE vendor_code IS NOT NULL;

ALTER TABLE vendors
  DROP CONSTRAINT IF EXISTS fk_vendors_opening_bill;
ALTER TABLE vendors
  ADD CONSTRAINT fk_vendors_opening_bill
  FOREIGN KEY (company_id, opening_balance_bill_id)
  REFERENCES bills (company_id, id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS ix_vendors_opening_bill
  ON vendors (company_id, opening_balance_bill_id);

-- 2. Vendor code auto-assignment trigger (SUP-###### per company)
CREATE OR REPLACE FUNCTION fn_assign_vendor_code()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.vendor_code IS NULL OR BTRIM(NEW.vendor_code) = '' THEN
    SELECT 'SUP-' || LPAD((COALESCE(MAX(CAST(SUBSTRING(vendor_code FROM 5) AS INTEGER)), 0) + 1)::TEXT, 6, '0')
      INTO NEW.vendor_code
      FROM vendors
     WHERE company_id = NEW.company_id
       AND vendor_code LIKE 'SUP-%';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_vendors_assign_code ON vendors;
CREATE TRIGGER trg_vendors_assign_code
  BEFORE INSERT ON vendors
  FOR EACH ROW EXECUTE FUNCTION fn_assign_vendor_code();

-- 3. Supplier statement archive and delivery metadata
CREATE TABLE IF NOT EXISTS vendor_statements (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id       BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  vendor_id        BIGINT NOT NULL,
  statement_date   DATE NOT NULL,
  period_start     DATE NOT NULL,
  period_end       DATE NOT NULL,
  currency_code    CHAR(3) NOT NULL DEFAULT 'ZMW',
  opening_balance  NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  closing_balance  NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  snapshot_json    JSONB,
  emailed_at       TIMESTAMPTZ,
  created_by       BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_vendor_statements_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_vendor_statements_vendor FOREIGN KEY (company_id, vendor_id)
    REFERENCES vendors (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_vendor_statements_company_vendor
  ON vendor_statements (company_id, vendor_id, statement_date DESC, id DESC);

ALTER TABLE vendor_statements ENABLE ROW LEVEL SECURITY;
ALTER TABLE vendor_statements FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS p_vendor_statements_isolation ON vendor_statements;
CREATE POLICY p_vendor_statements_isolation ON vendor_statements
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

