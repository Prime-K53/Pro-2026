-- Migration 0082: Printing Contract Signing Ceremony
-- Append-only dual-signature records. The company must sign before the
-- customer (enforced in the service layer); rows are never updated or deleted.

CREATE TABLE IF NOT EXISTS contract_signatures (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  contract_id       BIGINT NOT NULL,
  signer_role       VARCHAR(16) NOT NULL CHECK (signer_role IN ('company','customer')),
  signer_name       VARCHAR(200) NOT NULL,
  method            VARCHAR(16) NOT NULL CHECK (method IN ('drawn','typed','upload')),
  signature_data    TEXT NOT NULL,
  document_version  VARCHAR(40),
  signed_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by        BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT uq_contract_signatures_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_contract_signatures_contract FOREIGN KEY (company_id, contract_id)
    REFERENCES printing_contracts (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_contract_signatures_contract
  ON contract_signatures (company_id, contract_id, signed_at ASC);

ALTER TABLE contract_signatures ENABLE ROW LEVEL SECURITY;
ALTER TABLE contract_signatures FORCE ROW LEVEL SECURITY;
CREATE POLICY p_contract_signatures_isolation ON contract_signatures
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

