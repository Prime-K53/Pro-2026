-- Prime ERP — V2 WS-1: POS cash-drawer movements and shift reconciliation.
--
-- Adds an explicit cash-movement ledger (cash-in, cash-out, paid-in/out,
-- deposits) that is scoped to a shift, plus the refund/deposit totals needed
-- for an auditable expected-cash calculation. No existing data is dropped.

-- 1. Cash movements ledger.
CREATE TABLE IF NOT EXISTS pos_cash_movements (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  shift_id      BIGINT NOT NULL REFERENCES pos_shifts(id) ON DELETE RESTRICT,
  movement_type TEXT NOT NULL CHECK (
    movement_type IN ('cash_in', 'cash_out', 'paid_in', 'paid_out', 'deposit')
  ),
  amount        NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  reason        TEXT,
  performed_by  BIGINT NOT NULL REFERENCES users(id),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pos_cash_movements_shift
  ON pos_cash_movements (company_id, shift_id);

ALTER TABLE pos_cash_movements ENABLE ROW LEVEL SECURITY;
ALTER TABLE pos_cash_movements FORCE ROW LEVEL SECURITY;
CREATE POLICY p_pos_cash_movements_isolation ON pos_cash_movements
  USING (company_id = app_current_company_id());

-- 2. Reconciliation totals persisted on the shift for audit.
ALTER TABLE pos_shifts
  ADD COLUMN IF NOT EXISTS cash_refunds NUMERIC(12,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS cash_deposits NUMERIC(12,2) NOT NULL DEFAULT 0;