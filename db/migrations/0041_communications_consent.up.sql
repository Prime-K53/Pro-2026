CREATE TABLE IF NOT EXISTS communication_consents (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  customer_id   BIGINT NOT NULL,
  channel       TEXT NOT NULL CHECK (channel IN ('email', 'sms', 'whatsapp')),
  consent_type  TEXT NOT NULL CHECK (consent_type IN ('marketing', 'transactional', 'both')),
  status        TEXT NOT NULL DEFAULT 'granted' CHECK (status IN ('granted', 'withdrawn')),
  source        TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_communication_consents_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_communication_consents_customer FOREIGN KEY (company_id, customer_id)
    REFERENCES customers (company_id, id) ON DELETE CASCADE
);

CREATE INDEX idx_communication_consents_company ON communication_consents (company_id);
CREATE INDEX idx_communication_consents_customer ON communication_consents (company_id, customer_id);

CREATE TRIGGER trg_communication_consents_updated_at
  BEFORE UPDATE ON communication_consents
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE communication_consents ENABLE ROW LEVEL SECURITY;
ALTER TABLE communication_consents FORCE ROW LEVEL SECURITY;
CREATE POLICY p_communication_consents_isolation ON communication_consents
  USING (company_id = app_current_company_id());

