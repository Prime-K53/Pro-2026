-- Migration 0036: Customers — Contacts & Branches.
--
-- Adds Phase 4 customer management: contact persons and branch hierarchy.

-- 1. Customer Contacts — multiple contact persons per customer.
CREATE TABLE IF NOT EXISTS customer_contacts (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  customer_id  BIGINT NOT NULL,
  contact_name TEXT NOT NULL,
  role         TEXT,
  email        TEXT,
  phone        TEXT,
  is_primary   BOOLEAN NOT NULL DEFAULT FALSE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_customer_contacts_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_customer_contacts_customer FOREIGN KEY (company_id, customer_id)
    REFERENCES customers (company_id, id) ON DELETE CASCADE
);

CREATE INDEX idx_customer_contacts_company ON customer_contacts (company_id);
CREATE INDEX idx_customer_contacts_customer ON customer_contacts (company_id, customer_id);

CREATE TRIGGER trg_customer_contacts_updated_at
  BEFORE UPDATE ON customer_contacts
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE customer_contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_contacts FORCE ROW LEVEL SECURITY;
CREATE POLICY p_customer_contacts_isolation ON customer_contacts
  USING (company_id = app_current_company_id());

-- 2. Customer Branches — branch hierarchy per customer.
CREATE TABLE IF NOT EXISTS customer_branches (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id            BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  customer_id           BIGINT NOT NULL,
  branch_name           TEXT NOT NULL,
  address               TEXT,
  phone                 TEXT,
  is_billing_default    BOOLEAN NOT NULL DEFAULT FALSE,
  is_shipping_default   BOOLEAN NOT NULL DEFAULT FALSE,
  delivery_instructions TEXT,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_customer_branches_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_customer_branches_customer FOREIGN KEY (company_id, customer_id)
    REFERENCES customers (company_id, id) ON DELETE CASCADE
);

CREATE INDEX idx_customer_branches_company ON customer_branches (company_id);
CREATE INDEX idx_customer_branches_customer ON customer_branches (company_id, customer_id);

CREATE TRIGGER trg_customer_branches_updated_at
  BEFORE UPDATE ON customer_branches
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE customer_branches ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_branches FORCE ROW LEVEL SECURITY;
CREATE POLICY p_customer_branches_isolation ON customer_branches
  USING (company_id = app_current_company_id());