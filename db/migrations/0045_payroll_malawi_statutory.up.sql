-- Prime ERP — V2 WS-4: configurable Malawi statutory payroll.
--
-- Rates are NOT hardcoded in the application. Each company configures
-- effective-dated PAYE bands and statutory rates (pension, etc.). A payroll
-- run refuses to execute until PAYE bands exist, so a missing configuration
-- fails loudly instead of silently under-taxing.

-- 1. Effective-dated PAYE bands.
CREATE TABLE IF NOT EXISTS payroll_paye_bands (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  lower_bound    NUMERIC(19,4) NOT NULL CHECK (lower_bound >= 0),
  upper_bound    NUMERIC(19,4) CHECK (upper_bound IS NULL OR upper_bound > lower_bound),
  rate           NUMERIC(9,6) NOT NULL CHECK (rate >= 0 AND rate <= 1),
  effective_from DATE NOT NULL,
  effective_to   DATE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_payroll_paye_bands_company
  ON payroll_paye_bands (company_id, effective_from);

ALTER TABLE payroll_paye_bands ENABLE ROW LEVEL SECURITY;
ALTER TABLE payroll_paye_bands FORCE ROW LEVEL SECURITY;
CREATE POLICY p_payroll_paye_bands_isolation ON payroll_paye_bands
  USING (company_id = app_current_company_id());

-- 2. Effective-dated statutory rates (pension, other).
CREATE TABLE IF NOT EXISTS payroll_statutory_rates (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  rate_type      TEXT NOT NULL CHECK (
    rate_type IN ('pension_employee', 'pension_employer', 'other_statutory')
  ),
  rate           NUMERIC(9,6) NOT NULL CHECK (rate >= 0 AND rate <= 1),
  basis          TEXT NOT NULL DEFAULT 'gross' CHECK (basis IN ('gross', 'basic')),
  effective_from DATE NOT NULL,
  effective_to   DATE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_payroll_statutory_rates_company
  ON payroll_statutory_rates (company_id, effective_from);

ALTER TABLE payroll_statutory_rates ENABLE ROW LEVEL SECURITY;
ALTER TABLE payroll_statutory_rates FORCE ROW LEVEL SECURITY;
CREATE POLICY p_payroll_statutory_rates_isolation ON payroll_statutory_rates
  USING (company_id = app_current_company_id());

-- 3. Jurisdiction-neutral payslip columns (US columns remain for history).
ALTER TABLE pay_stubs
  ADD COLUMN IF NOT EXISTS paye              NUMERIC(19,4) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS pension_employee  NUMERIC(19,4) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS pension_employer  NUMERIC(19,4) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS other_deductions  NUMERIC(19,4) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS employer_other    NUMERIC(19,4) NOT NULL DEFAULT 0;