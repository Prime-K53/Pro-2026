-- 0017_inventory_ops_and_read_models.up.sql
--
-- Adds the read models and audit tables required by the advanced inventory
-- operations: stock counts, internal transfers, and stock damage write-offs.
--
-- Financial safety notes:
--   * No existing table is altered destructively. The only change to an
--     existing object is widening the inventory_movements.movement_type CHECK
--     so transfers/damages/count corrections can be represented.
--   * Every monetary/quantity column keeps NUMERIC(19,6). Variance and value
--     columns are GENERATED so they can never drift from their inputs.
--   * Every stock-affecting table carries a journal_txn_id so the perpetual
--     stock ledger can always be tied back to the general ledger.
--   * All tables mirror the existing RLS pattern (ENABLE + FORCE + isolation
--     policy) and the uq_<table>_company_id uniqueness convention.

-- 1. Widen movement_type so internal transfers, damage write-offs and count
--    corrections are first-class movements rather than masquerading as
--    'adjustment'. The constraint was created inline (unnamed) in 0005, so
--    PostgreSQL named it inventory_movements_movement_type_check.
ALTER TABLE inventory_movements
  DROP CONSTRAINT IF EXISTS inventory_movements_movement_type_check;

ALTER TABLE inventory_movements
  ADD CONSTRAINT inventory_movements_movement_type_check
  CHECK (movement_type IN (
    'purchase', 'sale', 'production_consume', 'adjustment',
    'return_in', 'return_out', 'void',
    'transfer', 'damage', 'count_adjust'
  ));

-- 2. Storage location on the item master. Transfers are meaningless without
--    at least a free-text location on the item; transfer headers carry the
--    explicit from/to pair for auditability.
ALTER TABLE inventory_items
  ADD COLUMN IF NOT EXISTS location TEXT;

-- 3. Deferrable-friendly index for ledger paging (newest movements first).
CREATE INDEX IF NOT EXISTS ix_inv_movements_item_created
  ON inventory_movements (company_id, item_id, movement_at DESC, id DESC);

-- 4. Stock count headers -----------------------------------------------------
CREATE TABLE stock_counts (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id       BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  count_number     VARCHAR(64) NOT NULL,
  count_date       DATE NOT NULL DEFAULT CURRENT_DATE,
  status           VARCHAR(16) NOT NULL DEFAULT 'draft'
                     CHECK (status IN ('draft', 'posted', 'voided')),
  journal_txn_id   BIGINT REFERENCES journal_transactions(id) ON DELETE SET NULL,
  notes            TEXT,
  created_by       BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_stock_counts_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_stock_counts_company_number UNIQUE (company_id, count_number)
);

CREATE INDEX ix_stock_counts_company_date
  ON stock_counts (company_id, count_date DESC);

ALTER TABLE stock_counts ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_counts FORCE ROW LEVEL SECURITY;
CREATE POLICY p_stock_counts_isolation ON stock_counts
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 5. Stock count lines ------------------------------------------------------
-- variance_qty / variance_value are GENERATED so a posted count can never
-- report a variance that disagrees with (counted - system) x unit_cost.
CREATE TABLE stock_count_lines (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  count_id       BIGINT NOT NULL REFERENCES stock_counts(id) ON DELETE CASCADE,
  item_id        BIGINT NOT NULL,
  variant_id     BIGINT,
  system_qty     NUMERIC(19, 6) NOT NULL DEFAULT 0.000000,
  counted_qty    NUMERIC(19, 6) NOT NULL DEFAULT 0.000000,
  unit_cost      NUMERIC(19, 6) NOT NULL DEFAULT 0.000000
                   CHECK (unit_cost >= 0),
  variance_qty   NUMERIC(19, 6)
                   GENERATED ALWAYS AS (counted_qty - system_qty) STORED,
  variance_value NUMERIC(19, 6)
                   GENERATED ALWAYS AS ((counted_qty - system_qty) * unit_cost) STORED,
  CONSTRAINT uq_stock_count_lines_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_stock_count_line_item FOREIGN KEY (company_id, item_id)
    REFERENCES inventory_items (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_stock_count_line_variant FOREIGN KEY (company_id, variant_id)
    REFERENCES item_variants (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_stock_count_lines_count
  ON stock_count_lines (company_id, count_id);

ALTER TABLE stock_count_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_count_lines FORCE ROW LEVEL SECURITY;
CREATE POLICY p_stock_count_lines_isolation ON stock_count_lines
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 6. Internal stock transfer headers ---------------------------------------
-- A transfer moves quantity between two locations inside the same company. It
-- is stock-neutral and GL-neutral: two mirrored movements at the same
-- avg_cost, net zero. No journal is posted unless a caller explicitly asks.
CREATE TABLE stock_transfers (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  transfer_number VARCHAR(64) NOT NULL,
  transfer_date   DATE NOT NULL DEFAULT CURRENT_DATE,
  from_location   TEXT NOT NULL,
  to_location     TEXT NOT NULL,
  status          VARCHAR(16) NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft', 'posted', 'voided')),
  notes           TEXT,
  created_by      BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_stock_transfers_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_stock_transfers_company_number UNIQUE (company_id, transfer_number),
  CONSTRAINT ck_stock_transfers_distinct_locations CHECK (from_location <> to_location)
);

CREATE INDEX ix_stock_transfers_company_date
  ON stock_transfers (company_id, transfer_date DESC);

ALTER TABLE stock_transfers ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_transfers FORCE ROW LEVEL SECURITY;
CREATE POLICY p_stock_transfers_isolation ON stock_transfers
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

CREATE TABLE stock_transfer_lines (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  transfer_id BIGINT NOT NULL REFERENCES stock_transfers(id) ON DELETE CASCADE,
  item_id     BIGINT NOT NULL,
  variant_id  BIGINT,
  quantity    NUMERIC(19, 6) NOT NULL CHECK (quantity > 0),
  unit_cost   NUMERIC(19, 6) NOT NULL DEFAULT 0.000000 CHECK (unit_cost >= 0),
  CONSTRAINT uq_stock_transfer_lines_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_stock_transfer_line_item FOREIGN KEY (company_id, item_id)
    REFERENCES inventory_items (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_stock_transfer_line_variant FOREIGN KEY (company_id, variant_id)
    REFERENCES item_variants (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_stock_transfer_lines_transfer
  ON stock_transfer_lines (company_id, transfer_id);

ALTER TABLE stock_transfer_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_transfer_lines FORCE ROW LEVEL SECURITY;
CREATE POLICY p_stock_transfer_lines_isolation ON stock_transfer_lines
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 7. Stock damage / write-off register -------------------------------------
-- Previously damage was only expressible as a negative 'adjustment'. Keeping a
-- dedicated register preserves the reason code, the value, and the journal
-- link without changing how the GL entry is computed (same 59xx counter
-- account resolution as adjustInventoryStock).
CREATE TABLE stock_damages (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  item_id        BIGINT NOT NULL,
  variant_id     BIGINT,
  damage_date    DATE NOT NULL DEFAULT CURRENT_DATE,
  quantity       NUMERIC(19, 6) NOT NULL CHECK (quantity > 0),
  unit_cost      NUMERIC(19, 6) NOT NULL DEFAULT 0.000000 CHECK (unit_cost >= 0),
  reason_code    VARCHAR(40) NOT NULL DEFAULT 'damaged',
  reason         TEXT,
  journal_txn_id BIGINT REFERENCES journal_transactions(id) ON DELETE SET NULL,
  created_by     BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  value          NUMERIC(19, 6)
                   GENERATED ALWAYS AS (quantity * unit_cost) STORED,
  CONSTRAINT uq_stock_damages_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_stock_damage_item FOREIGN KEY (company_id, item_id)
    REFERENCES inventory_items (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_stock_damage_variant FOREIGN KEY (company_id, variant_id)
    REFERENCES item_variants (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_stock_damages_company_date
  ON stock_damages (company_id, damage_date DESC);
CREATE INDEX ix_stock_damages_item
  ON stock_damages (company_id, item_id, damage_date DESC);

ALTER TABLE stock_damages ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_damages FORCE ROW LEVEL SECURITY;
CREATE POLICY p_stock_damages_isolation ON stock_damages
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));