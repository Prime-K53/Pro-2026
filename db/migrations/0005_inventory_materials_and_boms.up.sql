-- Migration 0005: Paper Specifications, Materials, 4-Type Inventory Catalog, Variants, BOMs & Movements
-- Enforces:
--   - Exact NUMERIC(19,6) conversion factors & unit costs (no floating point)
--   - Non-stocked printed_product / printing_service invariant (on_hand = 0)
--   - Non-invoiceable raw_material invariant (cannot appear on invoice_lines)

-- 1. Paper Specifications
CREATE TABLE paper_specifications (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  spec_code       VARCHAR(40) NOT NULL,
  name            VARCHAR(160) NOT NULL,
  size_code       VARCHAR(16) NOT NULL CHECK (size_code IN ('A4', 'A3', 'A5', 'B5', 'Letter', 'Legal', 'Custom')),
  width_mm        NUMERIC(9, 2) NOT NULL CHECK (width_mm > 0),
  height_mm       NUMERIC(9, 2) NOT NULL CHECK (height_mm > 0),
  gsm             INTEGER NOT NULL CHECK (gsm BETWEEN 30 AND 600),
  finish          VARCHAR(32) NOT NULL DEFAULT 'uncoated' CHECK (finish IN ('uncoated', 'matte', 'gloss', 'satin', 'bond', 'newsprint', 'cardstock')),
  grain_direction VARCHAR(16) NOT NULL DEFAULT 'long' CHECK (grain_direction IN ('long', 'short')),
  color_shade     VARCHAR(60) NOT NULL DEFAULT 'White',
  sheets_per_ream INTEGER NOT NULL DEFAULT 500 CHECK (sheets_per_ream > 0),
  is_active       BOOLEAN NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_paper_specs_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_paper_specs_company_code UNIQUE (company_id, spec_code)
);

ALTER TABLE paper_specifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE paper_specifications FORCE ROW LEVEL SECURITY;
CREATE POLICY p_paper_specs_isolation ON paper_specifications
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 2. Inventory Items (4 explicit types)
CREATE TABLE inventory_items (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  sku               VARCHAR(64) NOT NULL,
  name              VARCHAR(200) NOT NULL,
  item_type         VARCHAR(24) NOT NULL CHECK (item_type IN ('raw_material', 'printed_product', 'stationery', 'printing_service')),
  description       TEXT,
  unit_cost         NUMERIC(19, 6) NOT NULL DEFAULT 0.000000 CHECK (unit_cost >= 0),
  avg_cost          NUMERIC(19, 6) NOT NULL DEFAULT 0.000000 CHECK (avg_cost >= 0),
  sales_price       NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (sales_price >= 0),
  on_hand           NUMERIC(19, 6) NOT NULL DEFAULT 0.000000 CHECK (on_hand >= 0),
  reorder_point     NUMERIC(19, 6) NOT NULL DEFAULT 0.000000 CHECK (reorder_point >= 0),
  purchase_unit     VARCHAR(40) NOT NULL DEFAULT 'Unit',
  usage_unit        VARCHAR(40) NOT NULL DEFAULT 'Unit',
  conversion_factor NUMERIC(19, 6) NOT NULL DEFAULT 1.000000 CHECK (conversion_factor > 0),
  paper_spec_id     BIGINT,
  is_taxable        BOOLEAN NOT NULL DEFAULT FALSE,
  allows_negative_price BOOLEAN NOT NULL DEFAULT FALSE,
  asset_account_id  BIGINT NOT NULL,
  cogs_account_id   BIGINT NOT NULL,
  income_account_id BIGINT NOT NULL,
  is_active         BOOLEAN NOT NULL DEFAULT TRUE,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_inventory_items_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_items_paper_spec FOREIGN KEY (company_id, paper_spec_id)
    REFERENCES paper_specifications (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_items_asset_acct FOREIGN KEY (company_id, asset_account_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_items_cogs_acct FOREIGN KEY (company_id, cogs_account_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_items_income_acct FOREIGN KEY (company_id, income_account_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT,
  -- Critical Domain Invariants:
  -- 1. printed_product and printing_service are non-stocked (on_hand must stay 0)
  CONSTRAINT ck_items_non_stocked_types CHECK (
    item_type IN ('raw_material', 'stationery') OR on_hand = 0
  ),
  -- 2. raw_material is used internally only (cannot carry customer selling price)
  CONSTRAINT ck_items_raw_material_not_for_sale CHECK (
    item_type <> 'raw_material' OR sales_price = 0
  )
);

CREATE UNIQUE INDEX uq_inventory_items_company_sku_lower ON inventory_items (company_id, LOWER(sku));
CREATE INDEX ix_inventory_items_company_type ON inventory_items (company_id, item_type, is_active);

CREATE TRIGGER trg_inventory_items_updated_at
  BEFORE UPDATE ON inventory_items
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE inventory_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory_items FORCE ROW LEVEL SECURITY;
