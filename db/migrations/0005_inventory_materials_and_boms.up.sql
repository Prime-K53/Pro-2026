-- Triggers: Reject raw_material items on customer invoices & validate variant/BOM parent types
CREATE OR REPLACE FUNCTION enforce_invoice_line_no_raw_material()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_type VARCHAR(24);
BEGIN
  IF NEW.item_id IS NOT NULL THEN
    SELECT item_type INTO v_type
      FROM inventory_items
     WHERE id = NEW.item_id AND company_id = NEW.company_id;
    IF v_type = 'raw_material' THEN
      RAISE EXCEPTION 'Raw material item % cannot be placed on customer invoice lines.', NEW.item_id
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION enforce_item_variant_rules()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_type VARCHAR(24);
BEGIN
  SELECT item_type INTO v_type
    FROM inventory_items
   WHERE id = NEW.item_id AND company_id = NEW.company_id;
  IF v_type NOT IN ('stationery', 'printed_product') THEN
    RAISE EXCEPTION 'Item % of type "%" does not support variants.', NEW.item_id, v_type
      USING ERRCODE = 'check_violation';
  END IF;
  IF v_type = 'printed_product' AND NEW.on_hand <> 0 THEN
    RAISE EXCEPTION 'Printed product variant must have on_hand = 0.'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION enforce_bom_raw_material_check()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_type VARCHAR(24);
BEGIN
  SELECT item_type INTO v_type
    FROM inventory_items
   WHERE id = NEW.raw_material_item_id AND company_id = NEW.company_id;
  IF v_type <> 'raw_material' THEN
    RAISE EXCEPTION 'BOM component % must reference a raw_material item (found %).', NEW.raw_material_item_id, v_type
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_invoice_lines_no_raw_material
  BEFORE INSERT OR UPDATE ON invoice_lines
  FOR EACH ROW EXECUTE FUNCTION enforce_invoice_line_no_raw_material();

CREATE TRIGGER trg_item_variants_type_check
  BEFORE INSERT OR UPDATE ON item_variants
  FOR EACH ROW EXECUTE FUNCTION enforce_item_variant_rules();

CREATE TRIGGER trg_item_bom_raw_check
  BEFORE INSERT OR UPDATE ON item_bom_components
  FOR EACH ROW EXECUTE FUNCTION enforce_bom_raw_material_check();
