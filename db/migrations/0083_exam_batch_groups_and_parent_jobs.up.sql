-- 0083_exam_batch_groups_and_parent_jobs
--
-- Additive support for automated, batch-level examination production and
-- consolidated school invoicing:
--   * exam_batch_groups      — one parent school-examination group per school
--                              assessment. Existing per-class
--                              exam_assessment_batches rows are preserved and
--                              linked to this group (Decision 1).
--   * printing_jobs.parent_job_id — one parent production job per group with
--                              subject-level child jobs (Decision 2).
--   * exam_batch_group_runs  — durable, independently recoverable checkpoint
--                              ledger for the one-click workflow (Decision 6).
--
-- The only relaxation of existing production invariants is scoped to
-- job_type = 'exam_batch' (organisational parent jobs carry no material
-- requirements). All child subject jobs retain their full material, costing
-- and quantity requirements (C-1).

BEGIN;

-- 1. Parent school-examination group -----------------------------------------

CREATE TABLE exam_batch_groups (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id         BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  school_customer_id BIGINT NOT NULL,
  assessment_name    VARCHAR(160) NOT NULL,
  group_reference    VARCHAR(64) NOT NULL,
  status             VARCHAR(24) NOT NULL DEFAULT 'draft'
                       CHECK (status IN ('draft', 'prepared', 'production_completed', 'qc_approved', 'delivered', 'invoiced', 'cancelled')),
  invoice_id         BIGINT,
  created_by         BIGINT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_exam_batch_groups_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_exam_batch_groups_identity UNIQUE (company_id, school_customer_id, assessment_name, group_reference),
  CONSTRAINT fk_exam_batch_groups_school FOREIGN KEY (company_id, school_customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_exam_batch_groups_invoice FOREIGN KEY (company_id, invoice_id)
    REFERENCES invoices (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_exam_batch_groups_company_status
  ON exam_batch_groups (company_id, status);

CREATE TRIGGER trg_exam_batch_groups_updated_at
  BEFORE UPDATE ON exam_batch_groups
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE exam_batch_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE exam_batch_groups FORCE ROW LEVEL SECURITY;
CREATE POLICY p_exam_batch_groups_isolation ON exam_batch_groups
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 2. Link existing per-class batches to the parent group ---------------------

ALTER TABLE exam_assessment_batches
  ADD COLUMN exam_batch_group_id BIGINT;

ALTER TABLE exam_assessment_batches
  ADD CONSTRAINT fk_exam_batches_group FOREIGN KEY (company_id, exam_batch_group_id)
    REFERENCES exam_batch_groups (company_id, id) ON DELETE RESTRICT;

CREATE INDEX ix_exam_batches_company_group
  ON exam_assessment_batches (company_id, exam_batch_group_id);

-- 3. Parent / child production jobs ------------------------------------------

ALTER TABLE printing_jobs
  ADD COLUMN parent_job_id BIGINT;

ALTER TABLE printing_jobs
  ADD CONSTRAINT fk_pjobs_parent FOREIGN KEY (company_id, parent_job_id)
    REFERENCES printing_jobs (company_id, id) ON DELETE RESTRICT;

CREATE INDEX ix_printing_jobs_company_parent
  ON printing_jobs (company_id, parent_job_id);

-- 3a. Extend job_type with the organisational 'exam_batch' parent type.
ALTER TABLE printing_jobs DROP CONSTRAINT IF EXISTS printing_jobs_job_type_check;
ALTER TABLE printing_jobs
  ADD CONSTRAINT printing_jobs_job_type_check
  CHECK (job_type IN ('quick_photocopy', 'type_and_printing', 'general_print', 'exam_paper', 'printed_product', 'exam_batch'));

-- 3b. Relax material / quantity requirements exclusively for exam_batch parents.
ALTER TABLE printing_jobs ALTER COLUMN raw_paper_item_id DROP NOT NULL;
ALTER TABLE printing_jobs ALTER COLUMN raw_toner_item_id DROP NOT NULL;

ALTER TABLE printing_jobs DROP CONSTRAINT IF EXISTS printing_jobs_pages_check;
ALTER TABLE printing_jobs
  ADD CONSTRAINT printing_jobs_pages_check
  CHECK (job_type = 'exam_batch' OR pages > 0);

ALTER TABLE printing_jobs DROP CONSTRAINT IF EXISTS printing_jobs_copies_check;
ALTER TABLE printing_jobs
  ADD CONSTRAINT printing_jobs_copies_check
  CHECK (job_type = 'exam_batch' OR copies > 0);

ALTER TABLE printing_jobs
  ADD CONSTRAINT printing_jobs_exam_batch_materials
  CHECK (job_type = 'exam_batch' OR (raw_paper_item_id IS NOT NULL AND raw_toner_item_id IS NOT NULL));

-- 4. Durable checkpoint ledger ------------------------------------------------

CREATE TABLE exam_batch_group_runs (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id           BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  exam_batch_group_id  BIGINT NOT NULL,
  idempotency_key      VARCHAR(128),
  last_checkpoint      VARCHAR(24) NOT NULL DEFAULT 'prepared'
                         CHECK (last_checkpoint IN ('prepared', 'production_completed', 'qc_approved', 'delivered', 'invoiced')),
  parent_job_id        BIGINT,
  invoice_id           BIGINT,
  production_completed_at TIMESTAMPTZ,
  qc_approved_at       TIMESTAMPTZ,
  delivered_at         TIMESTAMPTZ,
  invoiced_at          TIMESTAMPTZ,
  attempt              INTEGER NOT NULL DEFAULT 1,
  last_error           TEXT,
  prepared_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at         TIMESTAMPTZ,
  CONSTRAINT uq_exam_batch_group_runs_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_exam_batch_group_runs_key UNIQUE (company_id, idempotency_key),
  CONSTRAINT uq_exam_batch_group_runs_group UNIQUE (company_id, exam_batch_group_id),
  CONSTRAINT fk_exam_batch_group_runs_group FOREIGN KEY (company_id, exam_batch_group_id)
    REFERENCES exam_batch_groups (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_exam_batch_group_runs_company_checkpoint
  ON exam_batch_group_runs (company_id, last_checkpoint);

ALTER TABLE exam_batch_group_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE exam_batch_group_runs FORCE ROW LEVEL SECURITY;
CREATE POLICY p_exam_batch_group_runs_isolation ON exam_batch_group_runs
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

COMMIT;