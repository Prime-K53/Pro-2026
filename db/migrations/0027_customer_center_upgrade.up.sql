-- 1. Customer master additions
ALTER TABLE customers
  ADD COLUMN IF NOT EXISTS currency_code CHAR(3) NOT NULL DEFAULT 'ZMW',
  ADD COLUMN IF NOT EXISTS opening_balance_invoice_id BIGINT;

-- Existing customers inherit their company's base currency rather than the
-- column default, which would mislabel non-ZMW tenants.
UPDATE customers c
   SET currency_code = co.base_currency
  FROM companies co
 WHERE co.id = c.company_id
   AND c.currency_code = 'ZMW';

ALTER TABLE customers
  DROP CONSTRAINT IF EXISTS fk_customers_opening_invoice;
ALTER TABLE customers
  ADD CONSTRAINT fk_customers_opening_invoice
  FOREIGN KEY (company_id, opening_balance_invoice_id)
  REFERENCES invoices (company_id, id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS ix_customers_opening_invoice
  ON customers (company_id, opening_balance_invoice_id);

-- 2. Customer code auto-assignment trigger (CUST-###### per company)
CREATE OR REPLACE FUNCTION fn_assign_customer_code()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.customer_code IS NULL OR BTRIM(NEW.customer_code) = '' THEN
    SELECT 'CUST-' || LPAD((COALESCE(MAX(CAST(SUBSTRING(customer_code FROM 6) AS INTEGER)), 0) + 1)::TEXT, 6, '0')
      INTO NEW.customer_code
      FROM customers
     WHERE company_id = NEW.company_id
       AND customer_code LIKE 'CUST-%';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_customers_assign_code ON customers;
CREATE TRIGGER trg_customers_assign_code
  BEFORE INSERT ON customers
  FOR EACH ROW EXECUTE FUNCTION fn_assign_customer_code();

