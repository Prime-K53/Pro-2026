-- 6. Period-end FX revaluation (D-8)
CREATE TABLE IF NOT EXISTS fx_revaluation_runs (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  as_of_date     DATE NOT NULL,
  base_currency  CHAR(3) NOT NULL,
  status         VARCHAR(16) NOT NULL DEFAULT 'posted' CHECK (status IN ('posted', 'reversed')),
  total_gain     NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (total_gain >= 0),
  total_loss     NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (total_loss >= 0),
  journal_txn_id BIGINT,
  created_by     BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_fx_revaluation_runs_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_fx_revaluation_runs_company_date UNIQUE (company_id, as_of_date),
  CONSTRAINT fk_fx_revaluation_runs_journal FOREIGN KEY (company_id, journal_txn_id)
    REFERENCES journal_transactions (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_fx_revaluation_runs_company_date
  ON fx_revaluation_runs (company_id, as_of_date DESC, id DESC);

CREATE TABLE IF NOT EXISTS fx_revaluation_lines (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id            BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  run_id                BIGINT NOT NULL,
  customer_id           BIGINT NOT NULL,
  invoice_id            BIGINT NOT NULL,
  currency_code         CHAR(3) NOT NULL,
  foreign_balance       NUMERIC(19, 4) NOT NULL CHECK (foreign_balance >= 0),
  carrying_base_balance NUMERIC(19, 4) NOT NULL CHECK (carrying_base_balance >= 0),
  closing_rate          NUMERIC(19, 6) NOT NULL CHECK (closing_rate > 0),
  revalued_base_balance NUMERIC(19, 4) NOT NULL CHECK (revalued_base_balance >= 0),
  gain_loss             NUMERIC(19, 4) NOT NULL,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_fx_revaluation_lines_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_fx_revaluation_lines_run FOREIGN KEY (company_id, run_id)
    REFERENCES fx_revaluation_runs (company_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_fx_revaluation_lines_customer FOREIGN KEY (company_id, customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_fx_revaluation_lines_invoice FOREIGN KEY (company_id, invoice_id)
    REFERENCES invoices (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_fx_revaluation_lines_run
  ON fx_revaluation_lines (company_id, run_id, id);
CREATE INDEX IF NOT EXISTS ix_fx_revaluation_lines_invoice
  ON fx_revaluation_lines (company_id, invoice_id, id DESC);

