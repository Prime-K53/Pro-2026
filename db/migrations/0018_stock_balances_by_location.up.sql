-- 0018_stock_balances_by_location.up.sql
--
-- Per-location stock balances.
--
-- 0017 introduced stock_transfers / stock_transfer_lines so a company can move
-- quantity between storage locations. A transfer is only meaningful if stock is
-- actually tracked per location, so this migration adds that table.
--
-- Invariants enforced here (and re-checked in inventoryOpsService):
--   * qty >= 0                     — a location can never hold negative stock.
--   * (company_id, item_id, variant_id, location) is unique.
--   * For every item, SUM(qty) across its rows equals inventory_items.on_hand.
--     The service validates this on every write; the DB cannot express the
--     cross-row sum constraint, so it is asserted in code before COMMIT.
--
-- `inventory_items.on_hand` remains the single authoritative company-wide total
-- used by the general ledger, purchasing and production. stock_balances is the
-- spatial breakdown of that total and must never be read as a second source of
-- truth for valuation.

-- Records the storage location a movement relates to. NULL for movements that
-- are not location-scoped (purchases booked to the default location). A
-- transfer writes two mirrored rows: one negative (out of from_location) and
-- one positive (into to_location), netting to zero so the ledger is unchanged.
ALTER TABLE inventory_movements
  ADD COLUMN IF NOT EXISTS location TEXT;

-- New journal source types used by the advanced inventory operations.
ALTER TABLE journal_transactions
  DROP CONSTRAINT IF EXISTS journal_transactions_source_type_check;

ALTER TABLE journal_transactions
  ADD CONSTRAINT journal_transactions_source_type_check CHECK (source_type IN (
    'manual', 'invoice', 'sales_receipt', 'payment', 'credit_memo',
    'bill', 'bill_payment', 'vendor_credit', 'goods_receipt',
    'deposit', 'transfer', 'check', 'expense', 'credit_card_charge', 'bank_import',
    'payroll', 'reconciliation', 'inventory_adjustment', 'inventory_damage', 'stock_count', 'depreciation',
    'printing_contract', 'quick_print', 'exam_production',
    'production_wip', 'production_issue', 'production_operation', 'production_cogs', 'production_variance',
    'opening_balance', 'reversal', 'closing_entry', 'fx_gain_loss'
  ));

CREATE TABLE stock_balances (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  item_id    BIGINT NOT NULL,
  variant_id BIGINT,
  location   TEXT NOT NULL DEFAULT 'Main',
  qty        NUMERIC(19, 6) NOT NULL DEFAULT 0.000000 CHECK (qty >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_stock_balances_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_stock_balance_item FOREIGN KEY (company_id, item_id)
    REFERENCES inventory_items (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_stock_balance_variant FOREIGN KEY (company_id, variant_id)
    REFERENCES item_variants (company_id, id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_stock_balances_item_location
  ON stock_balances (company_id, item_id, COALESCE(variant_id, 0), lower(location));

CREATE INDEX ix_stock_balances_item
  ON stock_balances (company_id, item_id);

ALTER TABLE stock_balances ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_balances FORCE ROW LEVEL SECURITY;
CREATE POLICY p_stock_balances_isolation ON stock_balances
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- Index to support the "is this item referenced anywhere?" deactivation guard.
CREATE INDEX IF NOT EXISTS ix_bill_lines_item
