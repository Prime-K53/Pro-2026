-- Migration 0035: Security — 2FA (TOTP secrets, backup codes).
--
-- Adds Phase 3 security: two-factor authentication with TOTP secrets and backup codes.

-- 1. User 2FA Secrets — encrypted TOTP secret per user.
CREATE TABLE IF NOT EXISTS user_two_factor_secrets (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  secret_encrypted TEXT NOT NULL,
  enabled          BOOLEAN NOT NULL DEFAULT FALSE,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_user_two_factor_secrets_user_id UNIQUE (user_id)
);

CREATE TRIGGER trg_user_two_factor_secrets_updated_at
  BEFORE UPDATE ON user_two_factor_secrets
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 2. User Backup Codes — hashed, single-use backup codes.
CREATE TABLE IF NOT EXISTS user_backup_codes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code_hash  TEXT NOT NULL,
  used_at    TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_user_backup_codes_user ON user_backup_codes (user_id);