-- 1. Document version tracking on QR codes.
ALTER TABLE document_qr_codes
  ADD COLUMN IF NOT EXISTS document_version INT NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS document_hash TEXT;

-- 2. Communication templates with version tracking.
CREATE TABLE IF NOT EXISTS communication_templates (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  channel     TEXT NOT NULL CHECK (channel IN ('email', 'sms', 'whatsapp')),
  body        TEXT NOT NULL,
  version     INT NOT NULL DEFAULT 1,
  is_active   BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_communication_templates_company_id UNIQUE (company_id, id)
);

CREATE INDEX IF NOT EXISTS idx_communication_templates_company
  ON communication_templates (company_id, channel, name);

ALTER TABLE communication_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE communication_templates FORCE ROW LEVEL SECURITY;
CREATE POLICY p_communication_templates_isolation ON communication_templates
  USING (company_id = app_current_company_id());