-- Migration 0020: Company-Wide Customer Wallet Subledger
-- Scope:
--   * Customer wallets (one per customer/currency)
--   * Append-only wallet transactions
--   * Wallet allocations to contracts/invoices
--   * Company/year numbering counters + next_printing_number()
--   * companies.timezone (default Africa/Blantyre)
--   * journal source type 'customer_wallet'
--   * payments.payment_method 'Wallet'
--   * approval action types for wallet/contract operations
--   * RLS + FORCE RLS on all new tables

-- 1. Company timezone
ALTER TABLE companies
  ADD COLUMN IF NOT EXISTS timezone TEXT NOT NULL DEFAULT 'Africa/Blantyre';

-- 2. Numbering counters
CREATE TABLE printing_number_counters (
  company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  scope      VARCHAR(32) NOT NULL CHECK (scope IN ('contract','exam_paper','wallet_txn')),
  year       SMALLINT NOT NULL,
  last_value INTEGER NOT NULL DEFAULT 0 CHECK (last_value >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (company_id, scope, year)
);

ALTER TABLE printing_number_counters ENABLE ROW LEVEL SECURITY;
ALTER TABLE printing_number_counters FORCE ROW LEVEL SECURITY;
CREATE POLICY p_printing_number_counters_isolation ON printing_number_counters
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

CREATE OR REPLACE FUNCTION next_printing_number(
  p_company_id BIGINT,
  p_scope      TEXT,
  p_year       SMALLINT,
  p_prefix     TEXT,
  p_min_width  INT
) RETURNS TEXT
LANGUAGE plpgsql AS $$
DECLARE
  v_last    INT;
  v_current BIGINT;
BEGIN
  v_current := NULLIF(current_setting('app.current_company_id', true), '')::BIGINT;
  IF v_current IS NULL OR p_company_id IS DISTINCT FROM v_current THEN
    RAISE EXCEPTION 'PRINTING_NUMBER_COMPANY_MISMATCH' USING ERRCODE = 'P0001';
  END IF;
  IF p_scope NOT IN ('contract','exam_paper','wallet_txn') THEN
    RAISE EXCEPTION 'PRINTING_NUMBER_INVALID_SCOPE' USING ERRCODE = 'P0001';
  END IF;
  IF p_prefix IS NULL OR p_prefix = '' THEN
    RAISE EXCEPTION 'PRINTING_NUMBER_INVALID_PREFIX' USING ERRCODE = 'P0001';
  END IF;
  IF p_min_width IS NULL OR p_min_width < 1 OR p_min_width > 10 THEN
    RAISE EXCEPTION 'PRINTING_NUMBER_INVALID_WIDTH' USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO printing_number_counters (company_id, scope, year, last_value)
  VALUES (p_company_id, p_scope, p_year, 1)
  ON CONFLICT (company_id, scope, year)
  DO UPDATE SET last_value = printing_number_counters.last_value + 1,
                updated_at = NOW()
  RETURNING last_value INTO v_last;

  RETURN p_prefix || p_year::TEXT || '-' || LPAD(v_last::TEXT, p_min_width, '0');
END;
$$;

-- 3. Customer wallets
CREATE TABLE customer_wallets (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id           BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  customer_id          BIGINT NOT NULL,
  currency_code        CHAR(3) NOT NULL,
  liability_account_id BIGINT NOT NULL,
  balance              NUMERIC(19,4) NOT NULL DEFAULT 0.0000 CHECK (balance >= 0),
  status               VARCHAR(16) NOT NULL DEFAULT 'active'
                       CHECK (status IN ('active','frozen','closed')),
  version              INTEGER NOT NULL DEFAULT 1,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_customer_wallets_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_customer_wallets_customer_currency UNIQUE (company_id, customer_id, currency_code),
  CONSTRAINT fk_customer_wallets_customer FOREIGN KEY (company_id, customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_customer_wallets_liability FOREIGN KEY (company_id, liability_account_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_customer_wallets_company_customer
  ON customer_wallets (company_id, customer_id);
CREATE INDEX ix_customer_wallets_company_status
  ON customer_wallets (company_id, status);

