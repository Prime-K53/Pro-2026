-- Deferred balance validation: wallet.balance must equal the posted ledger.
CREATE OR REPLACE FUNCTION trg_customer_wallet_balance_check() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
  v_balance NUMERIC(19,4);
  v_wallet  NUMERIC(19,4);
BEGIN
  SELECT COALESCE(SUM(CASE WHEN direction = 'credit' THEN amount ELSE -amount END), 0)
    INTO v_balance
    FROM customer_wallet_transactions
   WHERE company_id = NEW.company_id
     AND wallet_id = NEW.wallet_id;

  SELECT balance INTO v_wallet
    FROM customer_wallets
   WHERE company_id = NEW.company_id
     AND id = NEW.wallet_id;

  IF v_wallet IS DISTINCT FROM v_balance THEN
    RAISE EXCEPTION 'WALLET_BALANCE_MISMATCH: wallet=%, ledger=%', v_wallet, v_balance
      USING ERRCODE = '23514';
  END IF;

  RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_customer_wallet_balance_check
  AFTER INSERT ON customer_wallet_transactions
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION trg_customer_wallet_balance_check();

