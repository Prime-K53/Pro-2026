-- Migration 0012: Phase 10 SlowBooks Data Migration, Checkpoint, Idempotency & Reconciliation Infrastructure
-- Supports:
--   - Repeatable, checkpointed, dry-run and live ETL from SlowBooks-Pro-2026
--   - Exact source identifier mapping & preservation (zero silent drops)
--   - Rejection, duplicate, archived/deleted, and deprecated vertical exception tracking
--   - Full financial & entity-count reconciliation snapshots + cutover sign-off gates

-- 1. Migration Batches (Coordinator Header)
CREATE TABLE IF NOT EXISTS migration_batches (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_key              VARCHAR(120) NOT NULL,
  source_system          VARCHAR(60) NOT NULL DEFAULT 'SlowBooks-Pro-2026',
  source_label           VARCHAR(255) NOT NULL,
  source_sha256          CHAR(64) NOT NULL,
  mode                   VARCHAR(20) NOT NULL CHECK (mode IN ('dry_run', 'execute')),
  status                 VARCHAR(24) NOT NULL DEFAULT 'running'
    CHECK (status IN ('running', 'completed', 'failed', 'rolled_back')),
  source_backup_path     TEXT,
  source_backup_sha256   CHAR(64),
  target_backup_path     TEXT,
  target_backup_sha256   CHAR(64),
  target_backup_json     JSONB,
  started_by             BIGINT REFERENCES users(id) ON DELETE SET NULL,
  started_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at           TIMESTAMPTZ,
  summary_json           JSONB NOT NULL DEFAULT '{}'::JSONB,
  reconciled             BOOLEAN NOT NULL DEFAULT FALSE,
  cutover_approved       BOOLEAN NOT NULL DEFAULT FALSE,
  signed_off_by          BIGINT REFERENCES users(id) ON DELETE SET NULL,
  signed_off_at          TIMESTAMPTZ,
  sign_off_notes         TEXT,
  rolled_back_by         BIGINT REFERENCES users(id) ON DELETE SET NULL,
  rolled_back_at         TIMESTAMPTZ,
  rollback_reason        TEXT,
  CONSTRAINT uq_migration_batches_key UNIQUE (batch_key)
);

CREATE INDEX IF NOT EXISTS ix_migration_batches_status_time
  ON migration_batches (status, started_at DESC);

-- 2. Per-Company Migration Runs (Tenant-scoped link between global batch & target company)
CREATE TABLE IF NOT EXISTS migration_company_runs (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id           BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  batch_id             BIGINT NOT NULL REFERENCES migration_batches(id) ON DELETE CASCADE,
  source_company_id    VARCHAR(100) NOT NULL,
  source_company_name  VARCHAR(250) NOT NULL,
  status               VARCHAR(24) NOT NULL DEFAULT 'running'
    CHECK (status IN ('running', 'completed', 'failed', 'rolled_back')),
  total_source_records INTEGER NOT NULL DEFAULT 0 CHECK (total_source_records >= 0),
  total_migrated       INTEGER NOT NULL DEFAULT 0 CHECK (total_migrated >= 0),
  total_deduplicated   INTEGER NOT NULL DEFAULT 0 CHECK (total_deduplicated >= 0),
  total_archived       INTEGER NOT NULL DEFAULT 0 CHECK (total_archived >= 0),
  total_rejected       INTEGER NOT NULL DEFAULT 0 CHECK (total_rejected >= 0),
  reconciled           BOOLEAN NOT NULL DEFAULT FALSE,
  cutover_approved     BOOLEAN NOT NULL DEFAULT FALSE,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_mig_company_run UNIQUE (company_id, batch_id)
);

CREATE TRIGGER trg_migration_company_runs_updated_at
  BEFORE UPDATE ON migration_company_runs
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE migration_company_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE migration_company_runs FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS p_migration_company_runs_isolation ON migration_company_runs;
CREATE POLICY p_migration_company_runs_isolation ON migration_company_runs
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 3. Per-Domain Checkpoints (Resumable & Repeatable Execution)
CREATE TABLE IF NOT EXISTS migration_checkpoints (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id         BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  batch_id           BIGINT NOT NULL REFERENCES migration_batches(id) ON DELETE CASCADE,
  domain_order       INTEGER NOT NULL CHECK (domain_order >= 1),
  domain_name        VARCHAR(80) NOT NULL,
  status             VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'in_progress', 'completed', 'skipped', 'rolled_back')),
  source_count       INTEGER NOT NULL DEFAULT 0 CHECK (source_count >= 0),
  migrated_count     INTEGER NOT NULL DEFAULT 0 CHECK (migrated_count >= 0),
  deduplicated_count INTEGER NOT NULL DEFAULT 0 CHECK (deduplicated_count >= 0),
  archived_count     INTEGER NOT NULL DEFAULT 0 CHECK (archived_count >= 0),
  rejected_count     INTEGER NOT NULL DEFAULT 0 CHECK (rejected_count >= 0),
  last_source_id     VARCHAR(120),
  checkpoint_meta    JSONB NOT NULL DEFAULT '{}'::JSONB,
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_mig_checkpoint_domain UNIQUE (company_id, batch_id, domain_name)
);

CREATE TRIGGER trg_migration_checkpoints_updated_at
  BEFORE UPDATE ON migration_checkpoints
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE migration_checkpoints ENABLE ROW LEVEL SECURITY;
ALTER TABLE migration_checkpoints FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS p_migration_checkpoints_isolation ON migration_checkpoints;
CREATE POLICY p_migration_checkpoints_isolation ON migration_checkpoints
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 4. Source Identifier Map (Preserves SlowBooks IDs, References & Idempotency)
CREATE TABLE IF NOT EXISTS migration_id_map (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  batch_id        BIGINT NOT NULL REFERENCES migration_batches(id) ON DELETE CASCADE,
  source_system   VARCHAR(60) NOT NULL DEFAULT 'SlowBooks-Pro-2026',
  source_entity   VARCHAR(80) NOT NULL,
  source_id       VARCHAR(120) NOT NULL,
  target_table    VARCHAR(80) NOT NULL,
  target_id       BIGINT NOT NULL,
  source_key_hash CHAR(64) NOT NULL,
  disposition     VARCHAR(32) NOT NULL DEFAULT 'migrated'
    CHECK (disposition IN ('migrated', 'merged_duplicate', 'archived_preserved', 'opening_balance')),
  metadata_json   JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_mig_id_map_source UNIQUE (company_id, source_system, source_entity, source_id)
);

CREATE INDEX IF NOT EXISTS ix_mig_id_map_target
  ON migration_id_map (company_id, target_table, target_id);

ALTER TABLE migration_id_map ENABLE ROW LEVEL SECURITY;
ALTER TABLE migration_id_map FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS p_migration_id_map_isolation ON migration_id_map;
CREATE POLICY p_migration_id_map_isolation ON migration_id_map
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 5. Migration Exceptions (Rejections, Duplicates, Deleted/Archived & Discrepancy Log)
CREATE TABLE IF NOT EXISTS migration_exceptions (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  batch_id          BIGINT NOT NULL REFERENCES migration_batches(id) ON DELETE CASCADE,
  source_entity     VARCHAR(80) NOT NULL,
  source_id         VARCHAR(120) NOT NULL,
  disposition       VARCHAR(32) NOT NULL
    CHECK (disposition IN (
      'rejected',
      'duplicate_merged',
      'archived_preserved',
      'deleted_preserved',
      'deprecated_vertical',
      'discrepancy_explained'
    )),
  reason_code       VARCHAR(64) NOT NULL,
  reason_detail     TEXT NOT NULL,
  financial_impact  NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  source_payload    JSONB NOT NULL DEFAULT '{}'::JSONB,
  resolution_status VARCHAR(20) NOT NULL DEFAULT 'open'
    CHECK (resolution_status IN ('open', 'resolved', 'accepted')),
  resolved_by       BIGINT REFERENCES users(id) ON DELETE SET NULL,
  resolved_at       TIMESTAMPTZ,
  resolution_note   TEXT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_mig_exceptions_company_batch
  ON migration_exceptions (company_id, batch_id, disposition, resolution_status);

ALTER TABLE migration_exceptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE migration_exceptions FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS p_migration_exceptions_isolation ON migration_exceptions;
CREATE POLICY p_migration_exceptions_isolation ON migration_exceptions
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 6. Financial & Entity-Count Reconciliation Snapshots
CREATE TABLE IF NOT EXISTS migration_reconciliation_snapshots (
  id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id                  BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  batch_id                    BIGINT NOT NULL REFERENCES migration_batches(id) ON DELETE CASCADE,
  as_of_date                  DATE NOT NULL,
  basis                       VARCHAR(12) NOT NULL DEFAULT 'accrual' CHECK (basis IN ('accrual', 'cash')),
  source_tb_debit             NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  source_tb_credit            NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  target_tb_debit             NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  target_tb_credit            NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  ar_source                   NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  ar_target                   NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  ap_source                   NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  ap_target                   NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  bank_source                 NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  bank_target                 NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  inventory_source            NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  inventory_target            NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  revenue_source              NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  revenue_target              NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  expenses_source             NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  expenses_target             NUMERIC(19, 4) NOT NULL DEFAULT 0.0000,
  all_balanced                BOOLEAN NOT NULL DEFAULT FALSE,
  counts_reconciled           BOOLEAN NOT NULL DEFAULT FALSE,
  open_rejected_count         INTEGER NOT NULL DEFAULT 0 CHECK (open_rejected_count >= 0),
  cutover_ready               BOOLEAN NOT NULL DEFAULT FALSE,
  report_json                 JSONB NOT NULL DEFAULT '{}'::JSONB,
  signed_off_by               BIGINT REFERENCES users(id) ON DELETE SET NULL,
  signed_off_at               TIMESTAMPTZ,
  sign_off_notes              TEXT,
  created_at                  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_mig_recon_company_batch
  ON migration_reconciliation_snapshots (company_id, batch_id, created_at DESC);

ALTER TABLE migration_reconciliation_snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE migration_reconciliation_snapshots FORCE ROW LEVEL SECURITY;
