-- Migration 0034: AI Assistant — Configuration, Conversations, Messages, Anomalies, Proposed Actions, Audit.
--
-- Adds Phase 2 AI assistant: provider config, conversation history, anomaly alerts,
-- proposed actions with maker-checker approval, and AI audit logging.

-- 1. AI Configuration — provider, encrypted API key, model selection.
CREATE TABLE IF NOT EXISTS ai_config (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  provider     TEXT NOT NULL CHECK (provider IN ('openrouter', 'gemini', 'openai', 'anthropic', 'other')),
  api_key_encrypted TEXT NOT NULL,
  model_name   TEXT NOT NULL,
  enabled      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_ai_config_company_id UNIQUE (company_id, id)
);

CREATE INDEX idx_ai_config_company ON ai_config (company_id);

CREATE TRIGGER trg_ai_config_updated_at
  BEFORE UPDATE ON ai_config
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE ai_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_config FORCE ROW LEVEL SECURITY;
CREATE POLICY p_ai_config_isolation ON ai_config
  USING (company_id = app_current_company_id());

-- 2. AI Conversations — per-user conversation threads.
CREATE TABLE IF NOT EXISTS ai_conversations (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  user_id      BIGINT NOT NULL REFERENCES users(id),
  title        TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_ai_conversations_company_id UNIQUE (company_id, id)
);

CREATE INDEX idx_ai_conversations_company ON ai_conversations (company_id);
CREATE INDEX idx_ai_conversations_user ON ai_conversations (company_id, user_id);

CREATE TRIGGER trg_ai_conversations_updated_at
  BEFORE UPDATE ON ai_conversations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE ai_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_conversations FORCE ROW LEVEL SECURITY;
CREATE POLICY p_ai_conversations_isolation ON ai_conversations
  USING (company_id = app_current_company_id());

-- 3. AI Messages — individual messages in a conversation.
CREATE TABLE IF NOT EXISTS ai_messages (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id       BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  conversation_id  BIGINT NOT NULL,
  role             TEXT NOT NULL CHECK (role IN ('user', 'assistant', 'system')),
  content          TEXT NOT NULL,
  source_citations JSONB,
  token_count      INTEGER,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_ai_messages_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_ai_messages_conversation FOREIGN KEY (company_id, conversation_id)
    REFERENCES ai_conversations (company_id, id) ON DELETE CASCADE
);

CREATE INDEX idx_ai_messages_company ON ai_messages (company_id);
CREATE INDEX idx_ai_messages_conversation ON ai_messages (company_id, conversation_id);

ALTER TABLE ai_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_messages FORCE ROW LEVEL SECURITY;
CREATE POLICY p_ai_messages_isolation ON ai_messages
  USING (company_id = app_current_company_id());

-- 4. AI Anomaly Alerts — detected anomalies with evidence.
CREATE TABLE IF NOT EXISTS ai_anomaly_alerts (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  anomaly_type TEXT NOT NULL,
  severity     TEXT NOT NULL CHECK (severity IN ('info', 'warning', 'alert', 'critical')),
  description  TEXT NOT NULL,
  evidence     JSONB,
  status       TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'acknowledged', 'resolved', 'dismissed')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at  TIMESTAMPTZ,
  CONSTRAINT uq_ai_anomaly_alerts_company_id UNIQUE (company_id, id)
);

CREATE INDEX idx_ai_anomaly_alerts_company ON ai_anomaly_alerts (company_id);
CREATE INDEX idx_ai_anomaly_alerts_status ON ai_anomaly_alerts (company_id, status);

ALTER TABLE ai_anomaly_alerts ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_anomaly_alerts FORCE ROW LEVEL SECURITY;
CREATE POLICY p_ai_anomaly_alerts_isolation ON ai_anomaly_alerts
  USING (company_id = app_current_company_id());

-- 5. AI Proposed Actions — action proposals requiring approval.
CREATE TABLE IF NOT EXISTS ai_proposed_actions (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id       BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  conversation_id  BIGINT,
  action_type      TEXT NOT NULL,
  description      TEXT NOT NULL,
  parameters       JSONB,
  status           TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'executed')),
  approval_id      BIGINT,
  created_by       BIGINT NOT NULL REFERENCES users(id),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_ai_proposed_actions_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_ai_proposed_actions_conversation FOREIGN KEY (company_id, conversation_id)
    REFERENCES ai_conversations (company_id, id) ON DELETE SET NULL
);

CREATE INDEX idx_ai_proposed_actions_company ON ai_proposed_actions (company_id);
CREATE INDEX idx_ai_proposed_actions_status ON ai_proposed_actions (company_id, status);

CREATE TRIGGER trg_ai_proposed_actions_updated_at
  BEFORE UPDATE ON ai_proposed_actions
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE ai_proposed_actions ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_proposed_actions FORCE ROW LEVEL SECURITY;
CREATE POLICY p_ai_proposed_actions_isolation ON ai_proposed_actions
  USING (company_id = app_current_company_id());

-- 6. AI Audit Logs — immutable log of AI queries and actions.
CREATE TABLE IF NOT EXISTS ai_audit_logs (
