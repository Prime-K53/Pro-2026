-- Prime ERP — V2 WS-4 R3: employee loans and other approved deductions.
--
-- Payroll applies the next loan installment (capped at the outstanding balance)
-- and active fixed/percentage deductions, then reduces the loan balance.

CREATE TABLE IF NOT EXISTS employee_loans (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  employee_id BIGINT NOT NULL,
  principal   NUMERIC(12,2) NOT NULL CHECK (principal > 0),
  balance     NUMERIC(12,2) NOT NULL CHECK (balance >= 0),
  installment NUMERIC(12,2) NOT NULL CHECK (installment > 0),
  status      TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'settled', 'cancelled')),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_employee_loans_employee FOREIGN KEY (company_id, employee_id)
    REFERENCES employees (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_employee_loans_company
  ON employee_loans (company_id, employee_id, status);

ALTER TABLE employee_loans ENABLE ROW LEVEL SECURITY;
ALTER TABLE employee_loans FORCE ROW LEVEL SECURITY;
CREATE POLICY p_employee_loans_isolation ON employee_loans
  USING (company_id = app_current_company_id());

CREATE TABLE IF NOT EXISTS employee_deductions (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id         BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  employee_id        BIGINT NOT NULL,
  deduction_type     TEXT NOT NULL,
  amount             NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  calculation_method TEXT NOT NULL DEFAULT 'fixed' CHECK (calculation_method IN ('fixed', 'percentage')),
  effective_from     DATE NOT NULL DEFAULT CURRENT_DATE,
  effective_to       DATE,
  status             TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_employee_deductions_employee FOREIGN KEY (company_id, employee_id)
    REFERENCES employees (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_employee_deductions_company
  ON employee_deductions (company_id, employee_id, status);

ALTER TABLE employee_deductions ENABLE ROW LEVEL SECURITY;
ALTER TABLE employee_deductions FORCE ROW LEVEL SECURITY;
CREATE POLICY p_employee_deductions_isolation ON employee_deductions
  USING (company_id = app_current_company_id());