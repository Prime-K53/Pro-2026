-- Migration 0002: Chart of Accounts, Fiscal Periods, Double-Entry General Ledger & Journals
-- Enforces balanced debit = credit constraint triggers, immutable posted transactions,
-- traceable reversals, and multi-company composite FK isolation.

-- 1. Chart of Accounts
CREATE TABLE accounts (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  code            VARCHAR(32),
  name            VARCHAR(160) NOT NULL,
  account_type    VARCHAR(32) NOT NULL CHECK (account_type IN (
    'Bank', 'AccountsReceivable', 'OtherCurrentAsset', 'Inventory', 'FixedAsset',
    'AccountsPayable', 'CreditCard', 'OtherCurrentLiability', 'PayrollLiability',
    'LongTermLiability', 'Equity', 'Income', 'CostOfGoodsSold', 'Expense', 'OtherExpense'
  )),
  detail_type     VARCHAR(40) NOT NULL DEFAULT 'other_current_asset',
  bank_kind       VARCHAR(20) CHECK (bank_kind IN ('bank', 'credit_card')),
  description     TEXT,
  parent_id       BIGINT,
  normal_balance  VARCHAR(6) NOT NULL CHECK (normal_balance IN ('debit', 'credit')),
  is_system       BOOLEAN NOT NULL DEFAULT FALSE,
  is_control      BOOLEAN NOT NULL DEFAULT FALSE,
  is_active       BOOLEAN NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_accounts_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_accounts_parent FOREIGN KEY (company_id, parent_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_accounts_company_code
  ON accounts (company_id, LOWER(code))
  WHERE code IS NOT NULL;

CREATE INDEX ix_accounts_company_type ON accounts (company_id, account_type, is_active);

CREATE TRIGGER trg_accounts_updated_at
  BEFORE UPDATE ON accounts
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE accounts FORCE ROW LEVEL SECURITY;
CREATE POLICY p_accounts_isolation ON accounts
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 2. Fiscal Periods (Closing Lock Enforcement)
CREATE TABLE fiscal_periods (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  period_name     VARCHAR(60) NOT NULL,
  start_date      DATE NOT NULL,
  end_date        DATE NOT NULL,
  status          VARCHAR(16) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'soft_closed', 'closed')),
  closed_by       BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  closed_at       TIMESTAMPTZ,
  CONSTRAINT ck_fiscal_period_dates CHECK (end_date >= start_date),
  CONSTRAINT uq_fiscal_periods_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_fiscal_periods_company_range UNIQUE (company_id, start_date, end_date)
);

ALTER TABLE fiscal_periods ENABLE ROW LEVEL SECURITY;
ALTER TABLE fiscal_periods FORCE ROW LEVEL SECURITY;
CREATE POLICY p_fiscal_periods_isolation ON fiscal_periods
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 3. Journal Transactions (Header)
CREATE TABLE journal_transactions (
  id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id                BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  entry_number              VARCHAR(64) NOT NULL,
  txn_date                  DATE NOT NULL,
  reference                 VARCHAR(100),
  description               TEXT,
  memo                      TEXT,
  source_type               VARCHAR(40) NOT NULL DEFAULT 'manual' CHECK (source_type IN (
    'manual', 'invoice', 'payment', 'credit_memo', 'bill', 'bill_payment', 'vendor_credit',
    'payroll', 'reconciliation', 'inventory_adjustment', 'depreciation',
    'printing_contract', 'quick_print', 'exam_production', 'opening_balance', 'reversal'
  )),
  source_id                 BIGINT,
  source_ref                VARCHAR(100),
  source_kind               VARCHAR(50),
  source_difference         NUMERIC(19, 4),
  class_id                  BIGINT,
  status                    VARCHAR(16) NOT NULL DEFAULT 'posted' CHECK (status IN ('draft', 'posted', 'voided')),
  is_posted                 BOOLEAN NOT NULL DEFAULT TRUE,
  is_adjusting              BOOLEAN NOT NULL DEFAULT FALSE,
  reverses_transaction_id   BIGINT,
  reversed_by_transaction_id BIGINT,
  posted_at                 TIMESTAMPTZ,
  posted_by                 BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  created_by                BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  created_at                TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_journal_txns_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_journal_txns_company_number UNIQUE (company_id, entry_number),
  CONSTRAINT fk_journal_txns_class FOREIGN KEY (company_id, class_id)
    REFERENCES txn_classes (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_journal_txns_reverses FOREIGN KEY (company_id, reverses_transaction_id)
    REFERENCES journal_transactions (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_journal_txns_reversed_by FOREIGN KEY (company_id, reversed_by_transaction_id)
    REFERENCES journal_transactions (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT ck_journal_no_self_reversal CHECK (
    reverses_transaction_id IS DISTINCT FROM id AND reversed_by_transaction_id IS DISTINCT FROM id
  )
);

CREATE INDEX ix_journal_txns_company_date ON journal_transactions (company_id, txn_date DESC);
CREATE INDEX ix_journal_txns_source ON journal_transactions (company_id, source_type, source_id);

ALTER TABLE journal_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE journal_transactions FORCE ROW LEVEL SECURITY;
CREATE POLICY p_journal_txns_isolation ON journal_transactions
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 4. Journal Lines (Double-Entry Debit / Credit Splits)
CREATE TABLE journal_lines (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  transaction_id  BIGINT NOT NULL,
  line_order      INTEGER NOT NULL DEFAULT 1 CHECK (line_order >= 1),
  account_id      BIGINT NOT NULL,
  basis           VARCHAR(10) NOT NULL DEFAULT 'both' CHECK (basis IN ('both', 'accrual', 'cash')),
  description     TEXT,
  debit           NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (debit >= 0),
  credit          NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (credit >= 0),
  class_id        BIGINT,
  party_type      VARCHAR(16) CHECK (party_type IN ('customer', 'vendor', 'employee')),
  party_id        BIGINT,
  is_reconciled   BOOLEAN NOT NULL DEFAULT FALSE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_journal_lines_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_journal_lines_txn FOREIGN KEY (company_id, transaction_id)
    REFERENCES journal_transactions (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_journal_lines_account FOREIGN KEY (company_id, account_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_journal_lines_class FOREIGN KEY (company_id, class_id)
    REFERENCES txn_classes (company_id, id) ON DELETE RESTRICT,
  -- Critical accounting invariant: a split line cannot have both debit > 0 and credit > 0
  CONSTRAINT ck_journal_line_single_side CHECK (NOT (debit > 0 AND credit > 0)),
  -- Critical accounting invariant: at least one side must be non-zero
  CONSTRAINT ck_journal_line_nonzero CHECK (debit > 0 OR credit > 0)
);

CREATE INDEX ix_journal_lines_company_txn ON journal_lines (company_id, transaction_id, line_order);
CREATE INDEX ix_journal_lines_company_account ON journal_lines (company_id, account_id, basis);

ALTER TABLE journal_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE journal_lines FORCE ROW LEVEL SECURITY;
CREATE POLICY p_journal_lines_isolation ON journal_lines
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 5. Deferred Constraint Trigger: Enforce Balanced Debits = Credits on Posted Journals at COMMIT
CREATE OR REPLACE FUNCTION enforce_balanced_journal()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_txn_id BIGINT;
  v_company_id BIGINT;
  v_is_posted BOOLEAN;
  v_line_count INTEGER;
  v_diff NUMERIC(19, 4);
  v_total NUMERIC(19, 4);
  v_txn_date DATE;
  v_source_type VARCHAR(40);
  v_closed_period VARCHAR(60);
BEGIN
  IF TG_TABLE_NAME = 'journal_transactions' THEN
    v_txn_id := COALESCE(NEW.id, OLD.id);
    v_company_id := COALESCE(NEW.company_id, OLD.company_id);
  ELSE
    v_txn_id := COALESCE(NEW.transaction_id, OLD.transaction_id);
    v_company_id := COALESCE(NEW.company_id, OLD.company_id);
  END IF;

  IF v_txn_id IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT is_posted, txn_date, source_type
    INTO v_is_posted, v_txn_date, v_source_type
    FROM journal_transactions
   WHERE id = v_txn_id AND company_id = v_company_id;

  IF NOT FOUND OR NOT v_is_posted THEN
    RETURN NULL;
  END IF;

  -- Check closed fiscal period lock (except explicit reversal or closing entries)
  SELECT period_name INTO v_closed_period
    FROM fiscal_periods
   WHERE company_id = v_company_id
     AND status = 'closed'
     AND v_txn_date BETWEEN start_date AND end_date
   LIMIT 1;

  IF v_closed_period IS NOT NULL AND v_source_type <> 'reversal' THEN
    RAISE EXCEPTION 'Cannot post journal % into closed fiscal period "%"', v_txn_id, v_closed_period
      USING ERRCODE = 'check_violation';
  END IF;

  -- Check accrual/both and cash/both views balance cleanly
  SELECT COUNT(*),
         COALESCE(SUM(debit), 0),
         COALESCE(SUM(debit - credit), 0)
    INTO v_line_count, v_total, v_diff
    FROM journal_lines
   WHERE transaction_id = v_txn_id
     AND company_id = v_company_id
     AND basis IN ('both', 'accrual');

  IF v_line_count > 0 AND v_diff <> 0 THEN
    RAISE EXCEPTION 'Unbalanced journal transaction % (company %): accrual/both debit-credit difference = %',
      v_txn_id, v_company_id, v_diff
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT COUNT(*),
         COALESCE(SUM(debit - credit), 0)
    INTO v_line_count, v_diff
    FROM journal_lines
   WHERE transaction_id = v_txn_id
     AND company_id = v_company_id
     AND basis IN ('both', 'cash');

  IF v_line_count > 0 AND v_diff <> 0 THEN
    RAISE EXCEPTION 'Unbalanced journal transaction % (company %): cash/both debit-credit difference = %',
      v_txn_id, v_company_id, v_diff
      USING ERRCODE = 'check_violation';
  END IF;

  IF v_total <= 0 AND NOT EXISTS (
    SELECT 1 FROM journal_lines WHERE transaction_id = v_txn_id AND company_id = v_company_id
  ) THEN
    RAISE EXCEPTION 'Posted journal transaction % has zero journal lines', v_txn_id
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_enforce_balanced_journal_txn
  AFTER INSERT OR UPDATE ON journal_transactions
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION enforce_balanced_journal();

CREATE CONSTRAINT TRIGGER trg_enforce_balanced_journal_line
  AFTER INSERT OR UPDATE OR DELETE ON journal_lines
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION enforce_balanced_journal();

-- 6. Immutability Guard: Prevent Silent Overwrites or Deletion of Posted Journal Entries
CREATE OR REPLACE FUNCTION prevent_posted_journal_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_is_posted BOOLEAN;
BEGIN
  IF TG_TABLE_NAME = 'journal_transactions' THEN
    IF OLD.is_posted THEN
      IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Posted journal transaction % cannot be deleted; post a reversal instead.', OLD.id
          USING ERRCODE = 'restrict_violation';
      END IF;
      -- Allow only controlled voiding / linking a reversal transaction without altering amount/date/description
      IF NEW.txn_date IS DISTINCT FROM OLD.txn_date
         OR NEW.entry_number IS DISTINCT FROM OLD.entry_number
         OR NEW.is_posted IS DISTINCT FROM OLD.is_posted
         OR NEW.company_id IS DISTINCT FROM OLD.company_id
      THEN
        RAISE EXCEPTION 'Posted journal transaction % is immutable; create a reversal entry instead.', OLD.id
          USING ERRCODE = 'restrict_violation';
      END IF;
      IF OLD.status = 'voided' AND NEW.status <> 'voided' THEN
        RAISE EXCEPTION 'Voided journal transaction % cannot be un-voided.', OLD.id
          USING ERRCODE = 'restrict_violation';
      END IF;
    END IF;
    RETURN NEW;
  END IF;

  -- journal_lines
  SELECT is_posted INTO v_is_posted
    FROM journal_transactions
   WHERE id = OLD.transaction_id AND company_id = OLD.company_id;

  IF v_is_posted THEN
    IF TG_OP = 'DELETE' THEN
      RAISE EXCEPTION 'Cannot delete line % of posted journal transaction %; post a reversal entry.', OLD.id, OLD.transaction_id
        USING ERRCODE = 'restrict_violation';
    END IF;
    -- Only reconciliation flag may toggle on a posted line
    IF NEW.account_id IS DISTINCT FROM OLD.account_id
       OR NEW.debit IS DISTINCT FROM OLD.debit
       OR NEW.credit IS DISTINCT FROM OLD.credit
       OR NEW.basis IS DISTINCT FROM OLD.basis
       OR NEW.transaction_id IS DISTINCT FROM OLD.transaction_id
       OR NEW.company_id IS DISTINCT FROM OLD.company_id
    THEN
      RAISE EXCEPTION 'Posted journal line % is immutable; post a reversal entry instead.', OLD.id
        USING ERRCODE = 'restrict_violation';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_prevent_posted_txn_mutation
  BEFORE UPDATE OR DELETE ON journal_transactions
  FOR EACH ROW EXECUTE FUNCTION prevent_posted_journal_mutation();

CREATE TRIGGER trg_prevent_posted_line_mutation
  BEFORE UPDATE OR DELETE ON journal_lines
  FOR EACH ROW EXECUTE FUNCTION prevent_posted_journal_mutation();
