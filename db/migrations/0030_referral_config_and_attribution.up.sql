-- Migration 0030: Referral Management — Campaign-level configuration, first-valid
-- attribution, budget reservation, fraud/dispute cases, reward qualification links
-- and referral approval action types.
--
-- Scope:
--   * Extend referral_campaigns with authoritative campaign-level financial terms
--     (rates, caps, approval threshold, eligible items, validity window, dates,
--     lifecycle, finance/management approvals, budget reserved/qualified counters).
--   * New referral_attributions (first-valid attribution, link/code/verbal).
--   * New referral_budget_reservations (deterministic exposure reservation).
--   * New referral_cases (fraud / dispute / exception case management).
--   * Extend referral_events (attribution / wallet / reversal / reservation /
--     approval / evidence / fraud-hold linkage; add 'reversed' status).
--   * Extend approval action-type constraints with referral governance actions.
--   * RLS + FORCE RLS on all new tables.
--
-- This migration is additive and reversible. All new financial configuration is
-- nullable (UNCONFIGURED) until explicitly supplied; activation is gated in the
-- service layer until mandatory configuration and approvals are recorded.

-- 1. Referral campaigns — authoritative campaign-level financial terms ---------
ALTER TABLE referral_campaigns
  ADD COLUMN IF NOT EXISTS referrer_reward_type VARCHAR(24)
    CHECK (referrer_reward_type IN ('fixed_credit', 'percent_commission', 'cash_payout')),
  ADD COLUMN IF NOT EXISTS referrer_reward_value NUMERIC(19, 4)
    CHECK (referrer_reward_value >= 0),
  ADD COLUMN IF NOT EXISTS referee_discount_type VARCHAR(24)
    CHECK (referee_discount_type IN ('percent', 'fixed_amount')),
  ADD COLUMN IF NOT EXISTS referee_discount_value NUMERIC(19, 4)
    CHECK (referee_discount_value >= 0),
  ADD COLUMN IF NOT EXISTS max_referrer_reward_per_order NUMERIC(19, 4)
    CHECK (max_referrer_reward_per_order >= 0),
  ADD COLUMN IF NOT EXISTS max_referee_discount_per_order NUMERIC(19, 4)
    CHECK (max_referee_discount_per_order >= 0),
  ADD COLUMN IF NOT EXISTS reward_approval_threshold NUMERIC(19, 4)
    CHECK (reward_approval_threshold >= 0),
  -- N1-C: 90-day attribution validity default, campaign-overridable.
  ADD COLUMN IF NOT EXISTS attribution_window_days INTEGER DEFAULT 90
    CHECK (attribution_window_days > 0),
  ADD COLUMN IF NOT EXISTS eligible_item_types TEXT[],
  ADD COLUMN IF NOT EXISTS eligible_item_ids BIGINT[],
  ADD COLUMN IF NOT EXISTS starts_at DATE,
  ADD COLUMN IF NOT EXISTS ends_at DATE,
  ADD COLUMN IF NOT EXISTS lifecycle_status VARCHAR(24) NOT NULL DEFAULT 'draft'
    CHECK (lifecycle_status IN ('draft', 'pending_approval', 'active', 'suspended', 'exhausted', 'completed', 'closed')),
  ADD COLUMN IF NOT EXISTS finance_approved_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS finance_approved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS management_approved_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS management_approved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS activated_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS suspended_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS suspension_reason TEXT,
  ADD COLUMN IF NOT EXISTS budget_reserved_amount NUMERIC(19, 4) NOT NULL DEFAULT 0.0000
    CHECK (budget_reserved_amount >= 0),
  ADD COLUMN IF NOT EXISTS budget_qualified_amount NUMERIC(19, 4) NOT NULL DEFAULT 0.0000
    CHECK (budget_qualified_amount >= 0);

-- Widen the legacy status check to carry the new lifecycle vocabulary. The
-- authoritative gate is lifecycle_status; status is kept for backward compat.
ALTER TABLE referral_campaigns DROP CONSTRAINT IF EXISTS referral_campaigns_status_check;
ALTER TABLE referral_campaigns
  ADD CONSTRAINT referral_campaigns_status_check
  CHECK (status IN ('active', 'paused', 'completed', 'draft', 'pending_approval', 'suspended', 'exhausted', 'closed'));

CREATE INDEX IF NOT EXISTS ix_referral_campaigns_lifecycle
  ON referral_campaigns (company_id, lifecycle_status);

-- 2. Referral attributions — first-valid attribution (link / code / verbal) -----
CREATE TABLE IF NOT EXISTS referral_attributions (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id           BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  customer_id          BIGINT NOT NULL,
  referrer_customer_id BIGINT NOT NULL,
  program_id           BIGINT NOT NULL,
  campaign_id          BIGINT,
  referral_code_id     BIGINT,
  method               VARCHAR(16) NOT NULL CHECK (method IN ('link', 'code', 'verbal')),
  status               VARCHAR(16) NOT NULL DEFAULT 'active'
                       CHECK (status IN ('active', 'superseded', 'expired', 'voided')),
  source_context       VARCHAR(64),
  attributed_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  attributed_by        BIGINT REFERENCES users(id) ON DELETE SET NULL,
  valid_until          TIMESTAMPTZ,
  locked               BOOLEAN NOT NULL DEFAULT TRUE,
  terms_snapshot       JSONB,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_referral_attributions_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_ref_attr_customer FOREIGN KEY (company_id, customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_ref_attr_referrer FOREIGN KEY (company_id, referrer_customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_ref_attr_program FOREIGN KEY (company_id, program_id)
    REFERENCES referral_programs (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_ref_attr_campaign FOREIGN KEY (company_id, campaign_id)
    REFERENCES referral_campaigns (company_id, id) ON DELETE SET NULL,
  CONSTRAINT fk_ref_attr_code FOREIGN KEY (company_id, referral_code_id)
    REFERENCES referral_codes (company_id, id) ON DELETE SET NULL,
  CONSTRAINT ck_ref_attr_not_self CHECK (customer_id <> referrer_customer_id)
);

-- First-valid-attribution rule (T2-A / T5-A): at most one active attribution per
-- referred customer per company, enforced at the database level.
CREATE UNIQUE INDEX IF NOT EXISTS uq_referral_attributions_active
  ON referral_attributions (company_id, customer_id)
  WHERE status = 'active';

CREATE INDEX IF NOT EXISTS ix_referral_attributions_company_status
  ON referral_attributions (company_id, status, attributed_at DESC);
CREATE INDEX IF NOT EXISTS ix_referral_attributions_referrer
  ON referral_attributions (company_id, referrer_customer_id);

CREATE TRIGGER trg_referral_attributions_updated_at
  BEFORE UPDATE ON referral_attributions
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE referral_attributions ENABLE ROW LEVEL SECURITY;
ALTER TABLE referral_attributions FORCE ROW LEVEL SECURITY;
CREATE POLICY p_referral_attributions_isolation ON referral_attributions
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 3. Referral budget reservations — deterministic exposure reservation ----------
CREATE TABLE IF NOT EXISTS referral_budget_reservations (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  campaign_id    BIGINT NOT NULL,
  attribution_id BIGINT,
  order_ref      VARCHAR(128) NOT NULL,
  amount         NUMERIC(19, 4) NOT NULL CHECK (amount > 0),
  status         VARCHAR(16) NOT NULL DEFAULT 'reserved'
                 CHECK (status IN ('reserved', 'released', 'qualified')),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_referral_budget_reservations_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_ref_resv_campaign FOREIGN KEY (company_id, campaign_id)
    REFERENCES referral_campaigns (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_ref_resv_attribution FOREIGN KEY (company_id, attribution_id)
    REFERENCES referral_attributions (company_id, id) ON DELETE SET NULL
);

-- Duplicate reservation prevention: one live reservation per (campaign, attribution, order).
CREATE UNIQUE INDEX IF NOT EXISTS uq_referral_budget_reservations_key
  ON referral_budget_reservations (company_id, campaign_id, attribution_id, order_ref)
  WHERE status = 'reserved';

CREATE INDEX IF NOT EXISTS ix_referral_budget_reservations_campaign
  ON referral_budget_reservations (company_id, campaign_id, status);

CREATE TRIGGER trg_referral_budget_reservations_updated_at
  BEFORE UPDATE ON referral_budget_reservations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE referral_budget_reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE referral_budget_reservations FORCE ROW LEVEL SECURITY;
CREATE POLICY p_referral_budget_reservations_isolation ON referral_budget_reservations
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 4. Referral cases — fraud / dispute / exception case management ---------------
CREATE TABLE IF NOT EXISTS referral_cases (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id         BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  case_type          VARCHAR(24) NOT NULL
                     CHECK (case_type IN ('fraud', 'dispute', 'exception', 'eligibility_exception', 'attribution_change')),
  status             VARCHAR(24) NOT NULL DEFAULT 'open'
                     CHECK (status IN ('open', 'under_review', 'confirmed', 'dismissed', 'resolved')),
  attribution_id     BIGINT,
  referral_event_id  BIGINT,
  pos_order_id       BIGINT,
  evidence           JSONB,
  decision_reason    TEXT,
  decided_by         BIGINT REFERENCES users(id) ON DELETE SET NULL,
  reviewer_id        BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_by         BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  decided_at         TIMESTAMPTZ,
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_referral_cases_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_ref_cases_attribution FOREIGN KEY (company_id, attribution_id)
    REFERENCES referral_attributions (company_id, id) ON DELETE SET NULL,
  CONSTRAINT fk_ref_cases_event FOREIGN KEY (company_id, referral_event_id)
    REFERENCES referral_events (company_id, id) ON DELETE SET NULL,
  CONSTRAINT fk_ref_cases_pos FOREIGN KEY (company_id, pos_order_id)
    REFERENCES pos_orders (company_id, id) ON DELETE SET NULL,
  -- U5-B: the independent reviewer must differ from the original decision maker.
  CONSTRAINT ck_ref_cases_independent_reviewer CHECK (reviewer_id IS NULL OR decided_by IS NULL OR reviewer_id <> decided_by)
);

CREATE INDEX IF NOT EXISTS ix_referral_cases_company_status
  ON referral_cases (company_id, status, created_at DESC);

CREATE TRIGGER trg_referral_cases_updated_at
  BEFORE UPDATE ON referral_cases
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE referral_cases ENABLE ROW LEVEL SECURITY;
ALTER TABLE referral_cases FORCE ROW LEVEL SECURITY;
CREATE POLICY p_referral_cases_isolation ON referral_cases
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

