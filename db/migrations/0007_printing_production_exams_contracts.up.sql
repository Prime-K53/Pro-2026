  completed_assessments   SMALLINT NOT NULL DEFAULT 0 CHECK (completed_assessments >= 0),
  deposit_bank_account_id BIGINT NOT NULL,
  liability_account_id    BIGINT NOT NULL,
  deposit_journal_txn_id  BIGINT,
