-- Migration 0007: Printing Production System Domains
-- Covers:
--   - Machines (printing_machines)
--   - Printing Estimates (printing_estimates, printing_estimate_lines)
--   - School Printing Contracts & Dated Milestones (printing_contracts, contract_assessment_milestones)
--   - Examination Batches & Papers with Per-Learner Class Pricing (exam_assessment_batches, exam_papers)
--   - Printing Jobs (printing_jobs: quick_photocopy, type_and_printing, general_print, exam_paper, commercial_job)
--   - Production Operations (production_operations)
--   - Finishing (finishing_operations)
--   - Quality Control (quality_control_inspections)
--   - Delivery (delivery_notes, delivery_note_lines)

-- 1. Printing Machines (Equipment / Press Assets)
CREATE TABLE printing_machines (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id           BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  machine_code         VARCHAR(40) NOT NULL,
  name                 VARCHAR(160) NOT NULL,
  machine_type         VARCHAR(32) NOT NULL CHECK (machine_type IN ('digital_press', 'offset_press', 'photocopier', 'guillotine', 'stitcher', 'binder', 'laminator')),
  manufacturer         VARCHAR(100),
  model                VARCHAR(100),
  supports_duplex      BOOLEAN NOT NULL DEFAULT TRUE,
  max_paper_size       VARCHAR(16) NOT NULL DEFAULT 'A3' CHECK (max_paper_size IN ('A4', 'A3', 'B5', 'Letter', 'SRA3')),
  speed_ppm            INTEGER CHECK (speed_ppm IS NULL OR speed_ppm > 0),
  click_cost_per_imp   NUMERIC(19, 6) NOT NULL DEFAULT 0.000000 CHECK (click_cost_per_imp >= 0),
  meter_impressions    BIGINT NOT NULL DEFAULT 0 CHECK (meter_impressions >= 0),
  fixed_asset_id       BIGINT,
  status               VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'maintenance', 'offline', 'retired')),
  created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_printing_machines_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_printing_machines_company_code UNIQUE (company_id, machine_code),
  CONSTRAINT fk_machines_fixed_asset FOREIGN KEY (company_id, fixed_asset_id)
    REFERENCES fixed_assets (company_id, id) ON DELETE SET NULL
);

ALTER TABLE printing_machines ENABLE ROW LEVEL SECURITY;
ALTER TABLE printing_machines FORCE ROW LEVEL SECURITY;
CREATE POLICY p_printing_machines_isolation ON printing_machines
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

-- 2. Printing Estimates (Cost-Driven Press Quote Engine)
CREATE TABLE printing_estimates (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id            BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  estimate_number       VARCHAR(64) NOT NULL,
  customer_id           BIGINT NOT NULL,
  linked_estimate_id    BIGINT,
  title                 VARCHAR(200) NOT NULL,
  estimate_date         DATE NOT NULL,
  valid_until           DATE,
  status                VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'sent', 'accepted', 'rejected', 'converted')),
  total_material_cost   NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (total_material_cost >= 0),
  total_machine_cost    NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (total_machine_cost >= 0),
  total_finishing_cost  NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (total_finishing_cost >= 0),
  total_cost            NUMERIC(19, 4) GENERATED ALWAYS AS (total_material_cost + total_machine_cost + total_finishing_cost) STORED,
  manual_selling_price  NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (manual_selling_price >= 0),
  estimated_profit      NUMERIC(19, 4) GENERATED ALWAYS AS (manual_selling_price - (total_material_cost + total_machine_cost + total_finishing_cost)) STORED,
  notes                 TEXT,
  created_by            BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_print_est_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_print_est_company_num UNIQUE (company_id, estimate_number),
  CONSTRAINT fk_print_est_customer FOREIGN KEY (company_id, customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_print_est_sales_est FOREIGN KEY (company_id, linked_estimate_id)
    REFERENCES estimates (company_id, id) ON DELETE SET NULL
);

ALTER TABLE printing_estimates ENABLE ROW LEVEL SECURITY;
