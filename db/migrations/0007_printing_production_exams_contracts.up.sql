  CONSTRAINT uq_printing_contracts_company_id UNIQUE (company_id, id),
  CONSTRAINT uq_printing_contracts_company_num UNIQUE (company_id, contract_number),
  CONSTRAINT fk_contracts_customer FOREIGN KEY (company_id, school_customer_id)
    REFERENCES customers (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_contracts_bank_acct FOREIGN KEY (company_id, deposit_bank_account_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_contracts_liab_acct FOREIGN KEY (company_id, liability_account_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_contracts_journal FOREIGN KEY (company_id, deposit_journal_txn_id)
    REFERENCES journal_transactions (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT ck_contracts_dates CHECK (end_date >= start_date),
  CONSTRAINT ck_contracts_balance_cap CHECK (remaining_balance <= total_prepaid_amount),
