  end_date                DATE NOT NULL,
  total_prepaid_amount    NUMERIC(19, 4) NOT NULL CHECK (total_prepaid_amount > 0),
  total_assessments       SMALLINT NOT NULL CHECK (total_assessments BETWEEN 2 AND 5),
