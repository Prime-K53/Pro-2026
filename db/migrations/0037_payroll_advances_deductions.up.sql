-- 1. Salary Advances — advance + repayment schedule.
CREATE TABLE IF NOT EXISTS salary_advances (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id         BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  employee_id        BIGINT NOT NULL,
  amount             NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  repayment_schedule  JSONB NOT NULL DEFAULT '[]',
  status             TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'repaid', 'cancelled')),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_salary_advances_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_salary_advances_employee FOREIGN KEY (company_id, employee_id)
    REFERENCES employees (company_id, id) ON DELETE RESTRICT
);

CREATE INDEX idx_salary_advances_company ON salary_advances (company_id);
CREATE INDEX idx_salary_advances_employee ON salary_advances (company_id, employee_id);

CREATE TRIGGER trg_salary_advances_updated_at
  BEFORE UPDATE ON salary_advances
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE salary_advances ENABLE ROW LEVEL SECURITY;
ALTER TABLE salary_advances FORCE ROW LEVEL SECURITY;
CREATE POLICY p_salary_advances_isolation ON salary_advances
  USING (company_id = app_current_company_id());

