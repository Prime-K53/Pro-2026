-- Migration 0019: Smart Operations (Promotions, Referrals, Marketing Messages, Price Cards) & Full POS
-- Enforces:
--   - Exact NUMERIC(19,4) / NUMERIC(9,6) precision (zero floating-point columns)
--   - Multi-company composite foreign keys + FORCE ROW LEVEL SECURITY
--   - Expanded journal_transactions source_type constraint for POS, referral rewards & marketing expense
--   - Full privileges for least-privilege runtime role pms_app_role

-- 1. Expand Journal Source Types for POS & Smart Operations
ALTER TABLE journal_transactions
  DROP CONSTRAINT IF EXISTS journal_transactions_source_type_check;

ALTER TABLE journal_transactions
  ADD CONSTRAINT journal_transactions_source_type_check CHECK (source_type IN (
    'manual', 'invoice', 'sales_receipt', 'pos_sale', 'payment', 'credit_memo',
    'bill', 'bill_payment', 'vendor_credit', 'goods_receipt',
    'deposit', 'transfer', 'check', 'expense', 'credit_card_charge', 'bank_import',
    'payroll', 'reconciliation', 'inventory_adjustment', 'inventory_damage', 'stock_count', 'depreciation',
    'printing_contract', 'quick_print', 'exam_production',
    'production_wip', 'production_issue', 'production_operation', 'production_cogs', 'production_variance',
    'referral_reward', 'marketing_expense',
    'opening_balance', 'reversal', 'closing_entry', 'fx_gain_loss'
  ));

-- 2. Promotions & Discount Campaigns
CREATE TABLE promotions (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id           BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  code                 VARCHAR(64) NOT NULL,
  name                 VARCHAR(160) NOT NULL,
  description          TEXT,
  discount_type        VARCHAR(24) NOT NULL CHECK (discount_type IN ('percent', 'fixed_amount', 'bogo', 'bundle')),
  discount_value       NUMERIC(19, 4) NOT NULL CHECK (discount_value >= 0),
  min_order_amount     NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (min_order_amount >= 0),
  max_discount_amount  NUMERIC(19, 4) CHECK (max_discount_amount IS NULL OR max_discount_amount >= 0),
  applicable_item_type VARCHAR(32) CHECK (applicable_item_type IS NULL OR applicable_item_type IN ('all', 'stationery', 'printed_product', 'printing_service')),
  applicable_item_id   BIGINT,
  discount_account_id  BIGINT,
  starts_at            DATE,
  ends_at              DATE,
  usage_limit          INTEGER CHECK (usage_limit IS NULL OR usage_limit > 0),
  usage_count          INTEGER NOT NULL DEFAULT 0 CHECK (usage_count >= 0),
  promo_budget         NUMERIC(19, 4) NOT NULL DEFAULT 0.0000 CHECK (promo_budget >= 0),
  show_on_price_card   BOOLEAN NOT NULL DEFAULT TRUE,
  is_active            BOOLEAN NOT NULL DEFAULT TRUE,
  created_by           BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_promotions_company_id UNIQUE (company_id, id),
  CONSTRAINT fk_promotions_item FOREIGN KEY (company_id, applicable_item_id)
    REFERENCES inventory_items (company_id, id) ON DELETE SET NULL,
  CONSTRAINT fk_promotions_discount_acct FOREIGN KEY (company_id, discount_account_id)
    REFERENCES accounts (company_id, id) ON DELETE RESTRICT,
  CONSTRAINT ck_promotions_date_range CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at >= starts_at)
);

CREATE UNIQUE INDEX uq_promotions_company_code_lower ON promotions (company_id, LOWER(code));
CREATE INDEX ix_promotions_company_active ON promotions (company_id, is_active);

CREATE TRIGGER trg_promotions_updated_at
  BEFORE UPDATE ON promotions
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE promotions ENABLE ROW LEVEL SECURITY;
ALTER TABLE promotions FORCE ROW LEVEL SECURITY;
CREATE POLICY p_promotions_isolation ON promotions
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

