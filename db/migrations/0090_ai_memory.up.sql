-- Migration 0090: AI semantic memory chunks (Phase 2).
--
-- Company-scoped, RLS-isolated store of non-authoritative business context
-- (product descriptions, customer background, pricing content, document
-- descriptions). Embeddings are stored as JSONB number[] (pgvector is not
-- available on the embedded PGlite build — see Phase 0 feasibility outcome);
-- similarity is computed in application code. Current operational facts
-- (balances, prices, stock) are NEVER stored here — they are retrieved
-- deterministically from authoritative sources.

CREATE TABLE IF NOT EXISTS ai_memory_chunks (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id          BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  kind                TEXT NOT NULL,
  record_type         TEXT NOT NULL,
  record_id           BIGINT NOT NULL DEFAULT 0,
  content             TEXT NOT NULL,
  embedding           JSONB,
  embedding_model     TEXT,
  embedding_dimensions INTEGER,
  content_hash        CHAR(64) NOT NULL,
  source_updated_at   TIMESTAMPTZ,
  indexed_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  version             INTEGER NOT NULL DEFAULT 1,
  CONSTRAINT uq_ai_memory_chunks_company UNIQUE (company_id, kind, record_type, record_id)
);

CREATE INDEX IF NOT EXISTS idx_ai_memory_chunks_company_kind
  ON ai_memory_chunks (company_id, kind);

ALTER TABLE ai_memory_chunks ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_memory_chunks FORCE ROW LEVEL SECURITY;
CREATE POLICY p_ai_memory_chunks_isolation ON ai_memory_chunks
  USING (company_id = app_current_company_id());