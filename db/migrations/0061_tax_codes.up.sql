-- Migration 0061: Multi-rate tax engine.
--
-- Adds a per-company tax code registry (rate + jurisdiction) and lets an
-- invoice reference a tax code. When an invoice has a tax_code_id, its rate is
-- taken from that code instead of the single per-invoice flat rate; invoices
-- without a code keep the existing flat-rate behaviour (backward compatible).

CREATE TABLE IF NOT EXISTS tax_codes (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  code         VARCHAR(32) NOT NULL,
  name         VARCHAR(120) NOT NULL,
  rate         NUMERIC(9, 6) NOT NULL DEFAULT 0 CHECK (rate >= 0),
  jurisdiction VARCHAR(80) NOT NULL DEFAULT 'General',
  is_active    BOOLEAN NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_tax_codes_company_code UNIQUE (company_id, code),
  CONSTRAINT uq_tax_codes_company_id UNIQUE (company_id, id)
);

ALTER TABLE tax_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE tax_codes FORCE ROW LEVEL SECURITY;
CREATE POLICY p_tax_codes_isolation ON tax_codes
  USING (app_rls_allowed(company_id))
  WITH CHECK (app_rls_allowed(company_id));

ALTER TABLE invoices ADD COLUMN IF NOT EXISTS tax_code_id BIGINT;
ALTER TABLE invoices
  DROP CONSTRAINT IF EXISTS fk_invoices_tax_code;
ALTER TABLE invoices
  ADD CONSTRAINT fk_invoices_tax_code FOREIGN KEY (company_id, tax_code_id)
  REFERENCES tax_codes (company_id, id) ON DELETE SET NULL;